#!/usr/bin/env python3
"""PageDesk's sample PDFs are reproducible and independently valid.

    python3 tests/unit/t_pdfix.py

apps/pagedesk/samples/ is GENERATED by tools/os88pdfgen.py and committed so a
disk build needs no host step. This regenerates the lot into a temp directory
and requires byte equality with the committed copies - so a hand edit of a
sample, or a generator change that forgot to refresh them, fails here - and
asks `qpdf --check` (an independent reader; docs/PAGEDESK-SPEC.md 18.4) to
accept every valid sample. Without qpdf that half SKIPs and says so.

Also checked: the negative corpus README is what the generator writes, every
negative file is named in it, no negative file leaks into the samples folder,
and every sample's manifest line matches its bytes (size and SHA-256).
"""
import hashlib
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from harness import check, done, eq                       # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import os88pdfgen as gen                                  # noqa: E402

SAMPLES = os.path.join(ROOT, 'apps', 'pagedesk', 'samples')
NEGREADME = os.path.join(ROOT, 'tests', 'pdfneg', 'README.TXT')


def rd(p):
    with open(p, 'rb') as f:
        return f.read()


def qpdf():
    for d in os.environ.get('PATH', '').split(os.pathsep) + ['/opt/homebrew/bin', '/usr/local/bin']:
        p = os.path.join(d, 'qpdf')
        if os.access(p, os.X_OK):
            return p
    return None


with tempfile.TemporaryDirectory() as tmp:
    built = gen.build_all_samples()
    files = {n: d for n, (p, d) in built.items()}
    files['MANIFEST.TXT'] = gen.manifest(built).encode()
    gen.write_dir(tmp, files)
    want = sorted(files)
    have = sorted(os.listdir(SAMPLES)) if os.path.isdir(SAMPLES) else []
    eq(have, want, 'apps/pagedesk/samples holds exactly the generated files',
       'a stray or missing sample means the folder is not what os88pdfgen.py writes')
    for n in want:
        got = rd(os.path.join(SAMPLES, n)) if n in have else b''
        check(got == files[n], '%s is byte-identical to the regenerated one' % n,
              'run python3 tools/os88pdfgen.py apps/pagedesk/samples and commit', got=got, want=files[n])
    # a second generation in the same process is identical (no hidden state)
    again = gen.build_all_samples()
    for n, (p, d) in again.items():
        check(d == built[n][1], '%s regenerates identically' % n, 'the generator must be deterministic')
    # manifest lines match the bytes
    man = files['MANIFEST.TXT'].decode()
    for n, (p, d) in built.items():
        blk = man[man.index('file %s\n' % n):]
        blk = blk[:blk.index('\n\n')]
        check(('sha256 %s' % hashlib.sha256(d).hexdigest()) in blk and ('bytes %d\n' % len(d)) in blk,
              '%s manifest entry matches its bytes' % n)
    # the profile: only FLATE.PDF may name FlateDecode
    for n, (p, d) in built.items():
        check((b'/FlateDecode' in d) == (n == 'FLATE.PDF'), '%s: FlateDecode only in FLATE.PDF' % n,
              'every other sample must stay inside the XT profile, PAGEDESK-SPEC 1.3')
    total = sum(len(d) for p, d in built.values())
    check(total < 120 * 1024, 'the samples fit beside a ~150 KB package on a 360 KB disk (%d bytes)' % total,
          'PD-21: core samples small enough for a dedicated 360 KiB disk')
    q = qpdf()
    if q:
        for n in sorted(built):
            r = subprocess.run([q, '--check', os.path.join(SAMPLES, n)], capture_output=True)
            out = (r.stdout + r.stderr).decode('latin-1')
            check(r.returncode == 0 and 'WARNING' not in out, 'qpdf --check accepts %s' % n,
                  'an independent reader must call every valid sample valid', got=out[-300:], want='clean')
    else:
        print('t_pdfix: SKIP qpdf not installed; the independent validity half did NOT run')

    # negative corpus: README is generated text, every file is listed
    neg = gen.negative_files()
    eq(rd(NEGREADME).decode(), gen.negative_readme(neg), 'tests/pdfneg/README.TXT is what the generator writes',
       'regenerate with --negative and copy README.TXT')
    readme = rd(NEGREADME).decode()
    for name, data, layer, code, why in neg:
        check(re.search(r'^%s\s' % re.escape(name), readme, re.M) is not None, 'README lists %s' % name)
        check(re.fullmatch(r'PDE_[A-Z]+', code) is not None, '%s has a PDE_* expectation' % name)
        check(name not in have, '%s is not in the samples folder' % name,
              'a negative file must never sit among the valid samples')
    codes = set()
    hdr = open(os.path.join(ROOT, 'apps', 'pagedesk', 'pdabi.h')).read()
    for name, data, layer, code, why in neg:
        check(('#define %s ' % code) in hdr, '%s expects a code pdabi.h defines (%s)' % (name, code))

done('t_pdfix')

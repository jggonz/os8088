CD_ROW = 7                      # drv_tab's CDROM.DRV row on kern_big
DRVR_SIZE, DRVR_ERR = 16, 14
BIGLEN = 100001


class QH(object):
    """A private QEMU: the gate disk in A:, a blank scratch floppy in B:, and
    the ISO - or an empty drive - as the secondary master."""

    def __init__(self, tmp, sysimg, bimg, iso):
        self.sock = os.path.join(tmp, "qmp.sock")
        self.pid = os.path.join(tmp, "qemu.pid")
        self.pidn = None
        atexit.register(self.close)
        os88qemu.own(self.pid, self.sock)
        cd = ("file=%s,format=raw," % iso) if iso else ""
        subprocess.run(
            ["qemu-system-i386", "-machine", "pc,vmport=off", "-m", "4",
             "-drive", "file=%s,format=raw,if=floppy" % sysimg,
             "-drive", "file=%s,format=raw,if=floppy,index=1" % bimg,
             "-drive", "%sif=ide,index=2,media=cdrom" % cd,
             "-boot", "a", "-chardev", "msmouse,id=m0",
             "-serial", "chardev:m0", "-display", "none",
             "-qmp", "unix:%s,server,nowait" % self.sock,
             "-daemonize", "-pidfile", self.pid], check=True)
        self.pidn = int(open(self.pid).read().strip())

    def close(self):
        if self.pidn:
            try:
                os.kill(self.pidn, signal.SIGTERM)
                os88qemu.gone(self.pidn)
            except OSError:
                pass
            self.pidn = None

    def hmp(self, *cmds):
        return xmcheck.qmp(self.sock, *cmds)

    def read(self, linear, n):
        return bytes(xmcheck.read_bytes(self.sock, linear, n))

    def readseg(self, seg, off, n):
        return self.read((seg << 4) + off, n)

    def mouse(self, *args):
        subprocess.run([sys.executable, os.path.join(ROOT, "tools",
                                                     "mouse.py"), self.sock]
                       + [str(a) for a in args], check=True,
                       capture_output=True, cwd=ROOT)

    def done(self, cap=2.0):
        os88qemu.ui_done(self, xmcheck.sym, cap=cap)

    def click(self, x, y, cap=2.0):
        self.mouse("click", x, y)
        self.done(cap)

    def need(self, cond, what, secs=30):
        if not os88qemu.acted(self, cond, secs=secs, what=what, poll=0.1):
            raise RuntimeError("timed out waiting for %s" % what)


def front_on(ui, drv):
    """The front window, when it is a Disk window that has MOUNTED `drv`."""
    f = ui.front()
    if f is None or not f.visible:
        return None
    fs = ui.fs_of(f)
    return f if fs is not None and fs[0] == drv and fs[2] == 1 else None


def want_names(iso, folder):
    return sorted((n, t) for n, t, _s, _h, _e in iso.listed(*iso.folder(folder)))


def got_names(ui, w):
    return sorted((n, t) for n, t in ui.listing(w) if n != "..")


def compare(bad, tag, ui, w, iso, folder):
    want, got = want_names(iso, folder), got_names(ui, w)
    print("   %s %s lists %d entries%s" % (
        tag, folder or "the root", len(got),
        "" if got == want else " - NOT the reference's %d" % len(want)))
    if got != want:
        bad.append("%s %s: guest %r, reference %r" % (tag, folder or "root",
                                                      got, want))


def open_row(q, ui, w, name, drv, what):
    """Double-click `name` in Disk window `w`; wait for a mounted listing."""
    i, _ = ui.entry(name, w)
    xmcheck.dblclick(q.sock, *ui.row_xy(w, i - ui.scroll(w)))
    q.need(lambda: front_on(ui, drv) is not None and
           (what is None or what(front_on(ui, drv))), "%s to open" % name)
    q.done()
    return front_on(ui, drv)


def disc_leg(bad):
    iso_path = os88build.at("build/cdfix.iso")
    iso = os88cdiso.Iso(open(iso_path, "rb").read())
    try:
        syms = os88drvsym.symbols("cdrom.bin")
    except os88drvsym.Mismatch as e:
        sys.exit("cdrom: %s" % e)
    tmp = tempfile.mkdtemp(dir=os.path.join(ROOT, "build"))
    q = None
    try:
        sysimg = os.path.join(tmp, "sys.img")
        shutil.copy(os88build.at("build/cdromtest.img"), sysimg)
        bimg = os.path.join(tmp, "b.img")
        subprocess.run([sys.executable, "tools/os88disk.py", "-o", bimg,
                        "--size", "1440"], check=True, capture_output=True)
        q = QH(tmp, sysimg, bimg, iso_path)
        os88qemu.acted(q, lambda: os.path.exists(q.sock), secs=30,
                       what="the QMP socket")
        xmcheck.wait_desktop(q.sock, "cdrom")
        S = xmcheck.sym
        row = q.read(S("drv_tab") + CD_ROW * DRVR_SIZE, DRVR_SIZE)
        seg, err = struct.unpack_from("<H", row, geom.DRVR_SEG)[0], row[DRVR_ERR]
        if not seg:
            bad.append("1. CDROM.DRV is not loaded (DRVR_ERR %d) - SYSTEM.CFG's "
                       "bit 8 was not read, or attach refused QEMU's drive"
                       % err)
            return
        base = geom.drv_base(seg)
        cbase = struct.unpack("<H", q.read(base + syms["cd_base"], 2))[0]
        unit = q.read(base + syms["cd_unit"], 1)[0]
        model = q.read(base + syms["cd_model"], 41).split(b"\0")[0]
        vol = q.read(base + syms["cd_vol"], 1)[0]
        print("   1. CDROM.DRV at %04Xh: task file %03Xh unit %d, '%s', "
              "volume %d" % (seg, cbase, unit, model.decode("latin-1"), vol))
        if (cbase, unit) != (0x170, 0) or not model:
            bad.append("1. the drive was not found as QEMU's secondary master")
        if vol == 0xFF:
            bad.append("1. no volume was registered at DRVV_READY")
            return
        ui = os88ui.UI(q, mouse=object(), sym=S, verbose=False)
        x, y = geom.drive_pt(q, chr(ord("A") + vol), S)
        xmcheck.dblclick(q.sock, x, y)
        q.need(lambda: front_on(ui, vol) is not None, "the CD's window", 60)
        q.done()
        w = front_on(ui, vol)
        compare(bad, "2.", ui, w, iso, "")
        # --- 3: down two, up two, and a directory longer than a sector -----
        w = open_row(q, ui, w, "DOCS", vol, None)
        compare(bad, "3.", ui, w, iso, "DOCS")
        w = open_row(q, ui, w, "DEEP", vol, None)
        compare(bad, "3.", ui, w, iso, "DOCS/DEEP")
        w = open_row(q, ui, w, "..", vol,
                     lambda f: any(n == "DEEP" for n, _ in ui.listing(f)))
        compare(bad, "3. (..)", ui, w, iso, "DOCS")
        w = open_row(q, ui, w, "..", vol,
                     lambda f: any(n == "DOCS" for n, _ in ui.listing(f)))
        compare(bad, "3. (..)", ui, w, iso, "")
        w = open_row(q, ui, w, "MANY", vol, None)
        compare(bad, "3.", ui, w, iso, "MANY")
        w = open_row(q, ui, w, "..", vol,
                     lambda f: any(n == "MANY" for n, _ in ui.listing(f)))
        # --- 4: a package off the CD --------------------------------------
        before = set(o.i for o in ui.windows())
        i, _ = ui.entry("MINES.O88", w)
        xmcheck.dblclick(q.sock, *ui.row_xy(w, i - ui.scroll(w)))
        opened = os88qemu.acted(
            q, lambda: any(o.i not in before and o.visible
                           for o in ui.windows()), secs=30,
            what="Minesweeper")
        print("   4. MINES.O88 launches off the CD: %s" % opened)
        if not opened:
            bad.append("4. MINES.O88 off the CD did not open")
        # --- 5: BIG.BIN to B:, and its bytes ------------------------------
        if not front_on(ui, vol):
            ui_raise_cd(q, ui, vol)
            q.need(lambda: front_on(ui, vol) is not None, "the CD in front")
        w = front_on(ui, vol)
        i, _ = ui.entry("BIG.BIN", w)
        q.click(*ui.row_xy(w, i - ui.scroll(w)))
        rdxms.menu_pick(q, ui, "Edit", "Copy")
        bx, by = geom.drive_pt(q, "B", S)
        xmcheck.dblclick(q.sock, bx, by)
        q.need(lambda: front_on(ui, 1) is not None, "B:'s window", 30)
        q.done()
        rdxms.menu_pick(q, ui, "Edit", "Paste")
        q.need(lambda: q.read(S("fcp_busy"), 1)[0] == 0, "the paste", 300)
        q.done(4.0)
        ferr = q.read(S("fcp_err"), 1)[0]
        q.hmp("quit")
        q.close()
        q = None
        try:
            got = os88fat.Fat12(bimg).read("BIG.BIN")
        except Exception as e:                  # noqa: BLE001
            got, why = None, e
        want = os88cdiso.pattern(BIGLEN)
        if got == want:
            print("   5. BIG.BIN copied to B: is the reference's %d bytes "
                  "(fcp_err %d)" % (BIGLEN, ferr))
        else:
            first = None
            if got is not None:
                first = next((k for k in range(min(len(got), len(want)))
                              if got[k] != want[k]), min(len(got), len(want)))
            bad.append("5. BIG.BIN on B: is not the CD's bytes (fcp_err %d; "
                       "%s)" % (ferr, "not on B:: %s" % why if got is None
                                else "%d bytes, first wrong at %s"
                                % (len(got), first)))
    except Exception as e:                      # noqa: BLE001
        bad.append("the disc leg died: %s" % e)
    finally:
        if q is not None:
            q.close()
        shutil.rmtree(tmp, ignore_errors=True)


def bring(q, ui, w, i, rows=6):
    """Walk the selection down with the arrow key until entry i is on screen
    (SPEC.md 22.11) - os88ui.scroll_to's way, keys and not the scroll bar,
    with [FS_SCRL] read back rather than a row count assumed."""
    for _ in range(40):
        if 0 <= i - ui.scroll(w) <= rows:
            return
        q.hmp("sendkey down")
        os88qemu.pace(q, 0.3)
    raise RuntimeError("entry %d never came on screen" % i)


def player_bss(q, ui, S):
    """CDRack's loader-zeroed bss, by its own map: (window, linear address of
    os88_image_end, offset of cr_cdabuf in it), or None while it has no
    window."""
    import re
    d = tempfile.mkdtemp(dir=os.path.join(ROOT, "build"))
    mp, tmpbin = os.path.join(d, "cdrack.map"), os.path.join(d, "cr.bin")
    subprocess.run(["nasm", "-f", "bin", "-w+error", "-I", "apps/",
                    "-I", "apps/cdrack/", "-I", "drivers/cdrom/",
                    "-I", os.path.dirname(os88build.at("build/cdart.inc")) + "/",
                    "--before", "[map symbols %s]" % mp, "-o", tmpbin,
                    "apps/cdrack/cdrack.asm"], check=True)
    same = open(tmpbin, "rb").read() == open(
        os88build.at("build/cdrack.bin"), "rb").read()
    os.unlink(tmpbin)
    lines = open(mp).read().splitlines()
    shutil.rmtree(d, ignore_errors=True)
    if not same:
        raise RuntimeError("build/cdrack.bin is not this source's")
    sym = {}
    for line in lines:
        m = re.match(r"\s*([0-9A-F]+)\s+([0-9A-F]+)\s+(\w+)$", line)
        if m:
            sym[m.group(3)] = int(m.group(2), 16)
    end = sym["os88_image_end"]
    for o in ui.windows():
        if o.title == "CDRack" and o.visible:
            seg = struct.unpack("<H", q.read(S("wm_wins") + o.i * geom.WIN_SIZE
                                       + geom.W_SEG, 2))[0]
            return o, (seg << 4) + end, sym["cr_cdabuf"] - end
    return None


def cda_bytes(track, leadout, starts, lens):
    """SPEC.md 119.3.5's 44 bytes, from the TOC cd_simtoc makes."""
    def msf(f):
        m, r = divmod(f, 4500)
        return bytes([r % 75, r // 75, m, 0])
    out = b"RIFF" + struct.pack("<I", 36) + b"CDDA" + b"fmt "
    out += struct.pack("<IHH", 24, 1, track)
    out += struct.pack("<I", leadout ^ (len(starts) + 1) << 24)
    st, ln = starts[track - 2], lens[track - 2]
    out += struct.pack("<II", st, ln) + msf(st + 150) + msf(ln)
    return out


def sim_leg(bad):
    """--sim: the gate's CDROM.DRV (-DCDSIM_AUDIO) gives QEMU's one-track
    disc three audio tracks after it, 40, 30 and 20 seconds (cddisc.inc's
    cd_simtoc). The root then lists TRACK02..04.CDA; double-clicking
    TRACK02.CDA opens CDRack through its .CDA association, which
    reads the file - 44 bytes cd_mkcda composed - picks track 2 and asks the
    drive to play it. QEMU's drive refuses every audio command, so the player
    ends saying so (CPS_NOAUD), which is the honest end of this leg: the play
    itself is vm/386-cdrom's to show (SPEC.md 119.7)."""
    iso_path = os88build.at("build/cdfix.iso")
    iso = os88cdiso.Iso(open(iso_path, "rb").read())
    data_end = len(open(iso_path, "rb").read()) // 2048
    tmp = tempfile.mkdtemp(dir=os.path.join(ROOT, "build"))
    q = None
    try:
        syms = os88drvsym.symbols("cdromsim.bin")   # the sim build's own map
        sysimg = os.path.join(tmp, "sys.img")
        shutil.copy(os88build.at("build/cdromsim.img"), sysimg)
        bimg = os.path.join(tmp, "b.img")
        subprocess.run([sys.executable, "tools/os88disk.py", "-o", bimg,
                        "--size", "1440"], check=True, capture_output=True)
        q = QH(tmp, sysimg, bimg, iso_path)
        os88qemu.acted(q, lambda: os.path.exists(q.sock), secs=30,
                       what="the QMP socket")
        xmcheck.wait_desktop(q.sock, "cdrom")
        S = xmcheck.sym
        row = q.read(S("drv_tab") + CD_ROW * DRVR_SIZE, DRVR_SIZE)
        seg = struct.unpack_from("<H", row, geom.DRVR_SEG)[0]
        vol = q.read(geom.drv_base(seg) + syms["cd_vol"], 1)[0]
        ui = os88ui.UI(q, mouse=object(), sym=S, verbose=False)
        xmcheck.dblclick(q.sock, *geom.drive_pt(q, chr(ord("A") + vol), S))
        q.need(lambda: front_on(ui, vol) is not None, "the CD's window", 60)
        q.done()
        w = front_on(ui, vol)
        want = sorted(want_names(iso, "") + [("TRACK0%d.CDA" % t, 0)
                                              for t in (2, 3, 4)])
        got = got_names(ui, w)
        print("   S1. the root lists %d entries, the three tracks among them%s"
              % (len(got), "" if got == want else " - NOT the reference's"))
        if got != want:
            bad.append("S1. root: guest %r, want %r" % (got, want))
        i, _ = ui.entry("TRACK02.CDA", w)
        bring(q, ui, w, i)
        xmcheck.dblclick(q.sock, *ui.row_xy(w, i - ui.scroll(w)))
        box = {}

        def up():
            r = player_bss(q, ui, S)
            if r:
                box["b"], box["cda"] = r[1], r[2]
                return q.read(r[1] + r[2], 4) == b"RIFF"
            return False
        q.need(up, "CDRack to read TRACK02.CDA", 40)
        os88qemu.pace(q, 2)
        b = box["b"]
        st = q.read(b, 6)
        lens = [40 * 75, 30 * 75, 20 * 75]
        starts = [data_end, data_end + lens[0], data_end + lens[0] + lens[1]]
        cda = q.read(b + box["cda"], 44)
        expect = cda_bytes(2, starts[2] + lens[2], starts, lens)
        print("   S2. TRACK02.CDA opened CDRack: state %d, track %d of "
              "%d..%d; its 44 bytes %s" % (st[0], st[5], st[2], st[3],
                                          "are cd_mkcda's" if cda == expect
                                          else "DIFFER"))
        if cda != expect:
            bad.append("S2. TRACK02.CDA read %s, want %s" % (cda.hex(),
                                                          expect.hex()))
        if (st[2], st[3], st[5]) != (1, 4, 2):
            bad.append("S2. the player stands on track %d of %d..%d, not 2 "
                       "of 1..4" % (st[5], st[2], st[3]))
        if st[0] != 4:                          # CPS_NOAUD
            bad.append("S2. the player's state is %d, not CPS_NOAUD - QEMU's "
                       "drive refuses audio and it must say so" % st[0])
    except Exception as e:                      # noqa: BLE001
        bad.append("the sim leg died: %s" % e)
    finally:
        if q is not None:
            q.close()
        shutil.rmtree(tmp, ignore_errors=True)


def ui_raise_cd(q, ui, vol):
    """Bring the CD's Disk window to the front by its title bar."""
    for o in ui.windows():
        fs = ui.fs_of(o)
        if o.visible and fs is not None and fs[0] == vol:
            q.click(o.x + 30, o.y + 4)
            return


def empty_leg(bad):
    tmp = tempfile.mkdtemp(dir=os.path.join(ROOT, "build"))
    q = None
    try:
        sysimg = os.path.join(tmp, "sys.img")
        shutil.copy(os88build.at("build/cdromtest.img"), sysimg)
        bimg = os.path.join(tmp, "b.img")
        shutil.copy(os88build.at("build/apps.img"), bimg)
        q = QH(tmp, sysimg, bimg, None)
        os88qemu.acted(q, lambda: os.path.exists(q.sock), secs=30,
                       what="the QMP socket")
        xmcheck.wait_desktop(q.sock, "cdrom")
        S = xmcheck.sym
        syms = os88drvsym.symbols("cdrom.bin")
        row = q.read(S("drv_tab") + CD_ROW * DRVR_SIZE, DRVR_SIZE)
        seg = struct.unpack_from("<H", row, geom.DRVR_SEG)[0]
        if not seg:
            bad.append("E1. an empty drive is still a drive: the row did not "
                       "load (DRVR_ERR %d)" % row[DRVR_ERR])
            return
        vol = q.read(geom.drv_base(seg) + syms["cd_vol"], 1)[0]
        ui = os88ui.UI(q, mouse=object(), sym=S, verbose=False)
        x, y = geom.drive_pt(q, chr(ord("A") + vol), S)
        xmcheck.dblclick(q.sock, x, y)
        os88qemu.pace(q, 8)
        q.done(6.0)
        mounted = front_on(ui, vol) is not None
        print("   E1. the empty drive's zone: mounted %s" % mounted)
        if mounted:
            bad.append("E1. an empty drive mounted a volume")
        ax, ay = geom.drive_pt(q, "A", S)
        xmcheck.dblclick(q.sock, ax, ay)
        alive = os88qemu.acted(q, lambda: front_on(ui, 0) is not None,
                               secs=30, what="A:'s window")
        print("   E2. the machine carries on (A: opens): %s" % alive)
        if not alive:
            bad.append("E2. after the empty drive, A: did not open")
    except Exception as e:                      # noqa: BLE001
        bad.append("the empty leg died: %s" % e)
    finally:
        if q is not None:
            q.close()
        shutil.rmtree(tmp, ignore_errors=True)


def main():
    bad = []
    if "--empty" in sys.argv[1:]:
        empty_leg(bad)
    elif "--sim" in sys.argv[1:]:
        sim_leg(bad)
    else:
        disc_leg(bad)
        if "--disc" not in sys.argv[1:]:
            empty_leg(bad)
    for b in bad:
        print("   FAIL: %s" % b)
    print("cdrom: %s" % ("FAIL" if bad else "ok"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

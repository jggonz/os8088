#!/usr/bin/env python3
"""cdrom - SPEC.md 119.7: CDROM.DRV finds an ATAPI drive and serves its disc.

    make cdromtest && python3 tests/cdrom.py [--empty]

QEMU BY NAME: it is the one emulator here with a 286-class CPU AND an ATAPI
drive (`if=ide,index=2,media=cdrom`, the secondary master at 170h). MartyPC
has no IDE at all, and CDROM.DRV refuses an 8088 at attach (SPEC.md 119.2).

The disc is build/cdfix.iso, written by tools/os88cdiso.py, whose `list` is
the REFERENCE: every listing below is compared with what the reference says
CDROM.DRV must list - the 8.3 names (119.3.2) and the types.

  1. The row is loaded with no error, and the driver found QEMU's drive: task
     file 170h, unit 0, a model string from IDENTIFY PACKET DEVICE.
  2. The CD-ROM's desktop zone opens a window on its root, and the root lists
     what the reference lists - a name that mangles (`LONGFI~K.TEX`), one
     that was lower case, one with two dots, a package, a folder.
  3. DOCS, then DOCS\\DEEP, list right; `..` twice comes back to DOCS and to
     the root (FSV_CHDIR's parent handle, 119.3.3); MANY - sixty names, a
     directory longer than a sector - lists all sixty.
  4. MINES.O88 launches off the CD (the loader's FSV_READAT, 62.9.18).
  5. BIG.BIN - 100,001 generated bytes, over 64 KB and not a whole number of
     sectors - copied to B: with Edit > Copy and Edit > Paste is the bytes
     tools/os88cdiso.py's pattern() makes, read back off B:'s image on the
     host (the copy engine's FSV_READAT chain, partial sectors at both ends).

`--empty` is the drive with no disc: the row still loads and the zone is
there, a double-click mounts nothing (FSV_CHDIR answers FERR_NODISK) and the
machine carries on - the desktop answers a second double-click on A:.

Break on purpose: cd_hof's `shl ax, cl` taken out and step 3 fails (every
folder handle names the base sector); cd_bytes' partial copy given a wrong
start and step 5 fails at the first byte past 2,048.
"""

#!/usr/bin/env python3
"""PMDMA's D page: where the kernel's driver table and USBMOUSE.DRV's state
are in THIS build, as an include.

    python3 tests/pmdma/mkkern.py OUT.inc

PMDMA's D key prints every Drivers-page row as the kernel holds it, the
worker count drv_unload waits on, int 33h, and USBMOUSE.DRV's own mode bytes -
the field report it answers is a USB Mouse tick that will not come off on a
PicoMEM 1.x while Ethernet's does (docs/FIELD-NOTES.md 66). A package can
read the kernel's segment but has no slot that lists driver rows, so the
offsets come from the build: the kernel's off os88sym (which refuses a map
that does not describe build/kernel.bin), USBMOUSE.DRV's off a map of a
second assembly of the same source, checked byte-identical to the one that
ships.
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import os88sym  # noqa: E402

KSYMS = ("drv_tab", "drv_wcnt", "drv_fseg6")
KEQUS = ("DRV_MAX", "DRVC_POINT", "DRVC_SOUND", "DRVC_DISK", "DRVR_SIZE", "DRVR_SEG", "DRVR_TITLE", "DRVR_ENT",
         "DRVR_CLASS", "DRVR_WANT", "DRVR_ERR")
USYMS = ("um_pm", "um_alive", "um_stop", "um_btn")
# SOUND.DRV's stream record and counters, for the S key: the field report is a
# PicoMEM 1.x that copies a test stream at full rate and plays Tracker and the
# Video Player in bursts (docs/FIELD-NOTES.md 66)
SSYMS = ("sbl_under",
         "sbl_str_act", "sbl_str_state", "sbl_paused", "sbl_expect",
         "sbl_auto", "sbl_direct", "sbl_ext", "sbl_ring_on", "sbl_hisp",
         "sbl_wide", "sbl_tc", "sbl_half", "sbl_total", "sbl_consumed",
         "sbl_fed", "sbl_play", "sbl_valid", "sbl_wd", "sbl_wd_rst",
         "sbl_irq", "sbl_drqmask", "sbl_base", "sbl_rmask", "sbl_oflags")


def drvmap(tmp, name, src, incs, built, want, defs=()):
    """Offsets of WANT in a second assembly of SRC, refused unless it is
    byte-identical to BUILT (the image that ships)."""
    img = os.path.join(tmp, name + ".bin")
    mp = os.path.join(tmp, name + ".map")
    cmd = ["nasm", "-f", "bin", "-w+error"] + ["-D" + d for d in defs]
    for i in incs:
        cmd += ["-I", i]
    subprocess.check_call(cmd + ["-o", img, "--before", "[map all %s]" % mp,
                                 src], cwd=ROOT)
    if open(img, "rb").read() != open(
            os.path.join(ROOT, "build", built), "rb").read():
        sys.exit("mkkern: the map's assembly is not build/%s" % built)
    got = {}
    for ln in open(mp, encoding="latin-1"):
        f = ln.split()
        if len(f) >= 3 and f[-1] in want:
            got[f[-1]] = int(f[1], 16)
    for n in want:
        if n not in got:
            sys.exit("mkkern: %s is not in %s's map" % (n, built))
    return got


def main():
    out = sys.argv[1]
    s = os88sym.syms()
    e = os88sym.equates()
    lines = ["; generated by tests/pmdma/mkkern.py - do not edit"]
    for n in KSYMS:
        if os88sym.segment_of(n) != os88sym.KERNEL_SEG:
            sys.exit("mkkern: %s is not in KERNEL_SEG" % n)
        lines.append("PDK_%s equ 0x%04X" % (n.upper(), s[n]))
    for n in KEQUS:
        lines.append("PDK_%s equ %d" % (n, e[n]))
    with tempfile.TemporaryDirectory() as tmp:
        um = drvmap(tmp, "um", "drivers/usbmouse/usbmouse.asm",
                    ("drivers/", "drivers/usbmouse/", "apps/"),
                    "usbmouse.bin", USYMS)
        sd = drvmap(tmp, "sd", "drivers/sound/sound.asm",
                    ("drivers/sound/", "drivers/", "apps/"),
                    "sound.bin", SSYMS, ("PICOMEM",))  # the Makefile's
                                                          # SNDDEF, plain build
    for n in USYMS:
        lines.append("PDK_%s equ 0x%04X" % (n.upper(), um[n]))
    for n in SSYMS:
        lines.append("PDK_%s equ 0x%04X" % (n.upper(), sd[n]))
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

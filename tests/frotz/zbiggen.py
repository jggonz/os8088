#!/usr/bin/env python3
"""zbiggen: write tests/frotz's BIG story - a Z-machine program past 64KB.

    python3 tests/frotz/zbiggen.py -o build/zt/zbig5.inf --gold build/zt/ZBIG5.GLD
    inform6 -v5 build/zt/zbig5.inf build/zt/ZBIG.Z5

WHY IT IS GENERATED. Frotz holds a story in ONE heap claim and walks it by
32KB PAGE (apps/frotz/zmem.inc): a table of one segment per page, built at
load. On kern_mega every one of those is a SELECTOR (OSAPI_SEG's SEG_SUB) and
on every other kernel it is the claim's segment plus the page, so the same
binary runs both. What has to be exercised is everything that crosses a page:
a call into a routine in any page, a loop whose body straddles a boundary (a
backward @jump that wraps SI, zx_jrel; and a PC that walks over one, zm_norm),
a string read out of a high page (zm_map), and @verify walking the lot. The
stories the disk ships do all of that and cannot be fetched on every box (the
IF Archive is the network), and none of them is a measurement: their opening
turns are mostly text drawn on the screen. So the fixture is a program, and a
program 150KB long is thousands of lines of Inform - generated here rather
than committed, deterministically, so the same arguments make the same bytes.

WHAT IT DOES, one command per line at its prompt:

    go     calls every worker once. Each is a two-pass loop over a ~2KB body of
           16-bit arithmetic, array traffic in dynamic memory and calls to leaf
           routines that are themselves spread over every page; the sum of
           their answers is printed. Pure interpretation: one line of output
    text   decodes every high string into a stream 3 table (no drawing),
           twice, and prints a sum of the second pass's bytes - zm_map's
           whole traffic
    quit   @quit

and @verify runs ONCE, before the first prompt: it walks the whole file, and
os8088's Frotz sums the story AS IT STANDS (zx_verify), so it can only agree
with dfrotz before @aread has written the input buffer into dynamic memory.

THE ANSWER IS KNOWN WITHOUT A REFERENCE INTERPRETER. Every statement is
emitted as Inform and as the Python that does the same to 16-bit words, so
--gold writes what `go`, `text`, `go` must print. It was checked against
dfrotz when written (both versions, both sizes); the model is the gate's
reference so a box with no dfrotz still has one.
"""
import argparse
import random

ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
ap.add_argument("-o", "--out", required=True)
ap.add_argument("--workers", type=int, default=60)
ap.add_argument("--stmts", type=int, default=110,
                help="statements in each worker's loop body")
ap.add_argument("--strings", type=int, default=24)
ap.add_argument("--gold", help="write what VERIFY, `go`, `text`, `go` print")
args = ap.parse_args()

rnd = random.Random(8088)
NLEAF = 24
out = []
w = out.append

w('! GENERATED by tests/frotz/zbiggen.py - do not edit, do not commit.')
w('Global acc = 0;')
w('Global gk = 0;')
w('Array garr --> 16;')
w('Array inbuf -> 64;')
w('Array parsebuf -> 64;')
w('Array tbuf -> 1200;')
w('Array wtab --> %s;' % " ".join("W%d" % i for i in range(args.workers)))
w('Array ltab --> %s;' % " ".join("L%d" % i for i in range(NLEAF)))
w('Array stab --> %s;' % " ".join("S%d" % i for i in range(args.strings)))

w('''
[ Main c;
    print "^ZBIG^";
    Ver();
    for (::) {
        print "^> ";
        inbuf->0 = 60;
        inbuf->1 = 0;
        @aread inbuf parsebuf -> c;
        c = inbuf->2;
        if (c == 'q') { print "BYE^"; @quit; }
        if (c == 'g') { Go(); continue; }
        if (c == 't') { Text(); continue; }
        print "?^";
    }
];

[ Ver;
    @verify ?Vok;
    print "VERIFY bad^";
    rtrue;
.Vok;
    print "VERIFY ok^";
];

[ Go k;
    acc = 0;
    for (k = 0 : k < %d : k++)
        acc = acc + (wtab-->k)(acc & 255);
    Report(acc);
];

[ Text r s n i sum;
    sum = 0;
    for (r = 0 : r < 2 : r++)
        for (s = 0 : s < %d : s++) {
            @output_stream 3 tbuf;
            print (string) stab-->s;
            @output_stream -3;
            if (r == 0) continue;           ! decode twice, sum once
            n = (tbuf->0) * 256 + tbuf->1;
            for (i = 0 : i < n : i++) sum = sum + tbuf->(i + 2) * (i + 1);
        }
    print "TEXT ", sum, "^";
];
''' % (args.workers, args.strings))


# THE MODEL. Z-machine arithmetic is 16-bit two's complement; @div and @mod
# truncate toward zero (Standard 15, zopstest's div_neg); `>` is signed.
def u(v):
    return v & 0xFFFF


def s16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


def zdiv(a, b):
    a, b = s16(a), s16(b)
    q = abs(a) // abs(b)
    return u(q if (a < 0) == (b < 0) else -q)


def zmod(a, b):
    a, b = s16(a), s16(b)
    r = abs(a) % abs(b)
    return u(-r if a < 0 else r)


class St:
    garr = [0] * 16
    gk = 0
    leaves = []


def expr_stmt():
    """One statement: (its Inform, a function doing it to the locals)."""
    k = rnd.randrange(10)
    a = rnd.randrange(1, 97)
    b = rnd.randrange(16)
    if k == 0:
        m = a | 1

        def f(v):
            v["x"] = u(v["x"] * m + v["i"])
        return "x = x * %d + i;" % m, f
    if k == 1:
        mask = rnd.choice((255, 1023, 4095, 32767))

        def f(v):
            v["y"] = u(v["y"] + v["x"]) & mask
        return "y = (y + x) & %d;" % mask, f
    if k == 2:
        d = a % 7 + 2

        def f(v):
            v["x"] = v["x"] | zdiv(v["y"] & 1023, d)
        return "x = x | ((y & 1023) / %d);" % d, f
    if k == 3:
        bit = 1 << rnd.randrange(8)

        def f(v):
            v["y"] = u(v["y"] + (1 if v["x"] & bit else -1))
        return "if (x & %d) y++; else y--;" % bit, f
    if k == 4:
        def f(v):
            St.garr[b] = u(v["x"] + a)
        return "garr-->%d = x + %d;" % (b, a), f
    if k == 5:
        def f(v):
            v["x"] = u(v["x"] + St.garr[(v["i"] + b) & 15])
        return "x = x + garr-->((i + %d) & 15);" % b, f
    if k == 6:
        j = rnd.randrange(NLEAF)

        def f(v):
            v["x"] = u(v["x"] + St.leaves[j](v["y"] & 63))
        return "x = x + (ltab-->%d)(y & 63);" % j, f
    if k == 7:
        def f(v):
            v["y"] = u(v["y"] - zmod(v["x"], a + 3))
        return "y = y - (x %% %d);" % (a + 3), f
    if k == 8:
        def f(v):
            St.gk = u(St.gk + 1)
            v["x"] = u(v["x"] + St.gk)
        return "gk = gk + 1; x = x + gk;", f

    def f(v):
        v["x"] = u(v["x"] - a) if s16(v["y"]) > a * 30 else u(v["x"] + b)
    return "if (y > %d) x = x - %d; else x = x + %d;" % (a * 30, a, b), f


# Workers and leaves INTERLEAVED, so the leaves land in every page too and a
# call from a worker goes to a routine pages away.
workers = []
leaf = 0
for wi in range(args.workers):
    w('[ W%d n i x y;' % wi)
    w('    x = n + %d; y = %d;' % (wi, wi * 7))
    w('    for (i = 0 : i < 2 : i++) {')
    body = []
    for _ in range(args.stmts):
        text, fn = expr_stmt()
        w('        ' + text)
        body.append(fn)
    workers.append((wi, body))
    w('    }')
    w('    return x + y;')
    w('];')
    if wi % max(1, args.workers // NLEAF) == 0 and leaf < NLEAF:
        k, c = rnd.randrange(3, 40), rnd.randrange(100)
        w('[ L%d v; return (v * %d + %d) & 511; ];' % (leaf, k, c))
        St.leaves.append(lambda v, k=k, c=c: u(v * k + c) & 511)
        leaf += 1
while leaf < NLEAF:
    w('[ L%d v; return v + %d; ];' % (leaf, leaf))
    St.leaves.append(lambda v, n=leaf: u(v + n))
    leaf += 1

WORDS = ("the brass lantern glows over a twisty maze of little passages all "
         "alike while a grue waits in darkness beyond the white house and its "
         "boarded front door near forest path clearing canyon rainbow falls "
         "troll bridge treasure chest jewelled egg songbird sword of elvish "
         "workmanship").split()
texts = []
for si in range(args.strings):
    n = rnd.randrange(50, 90)
    text = " ".join(rnd.choice(WORDS) for _ in range(n)) + "."
    w('Constant S%d "%s";' % (si, text))
    texts.append(text)

# LAST in the source, so it is the highest routine in the story: its inline
# text is read out of the top page.
w('''[ Report v;
    print "GO ", v, " (inline text from the top of the story)^";
];''')

with open(args.out, "w") as f:
    f.write("\n".join(out) + "\n")


def go():
    acc = 0
    for wi, body in workers:
        v = {"x": u((acc & 255) + wi), "y": wi * 7}
        for i in range(2):
            v["i"] = i
            for fn in body:
                fn(v)
        acc = u(acc + u(v["x"] + v["y"]))
    return "GO %d (inline text from the top of the story)" % s16(acc)


def text_sum():
    tot = 0
    for t in texts:
        for i, ch in enumerate(t.encode("ascii")):
            tot = u(tot + ch * (i + 1))
    return "TEXT %d" % s16(tot)


if args.gold:
    # `go`, `text`, `go`: the second `go` differs from the first, the array
    # and gk persisting across commands
    with open(args.gold, "w") as f:
        f.write("\n".join(["VERIFY ok", go(), text_sum(), go()]) + "\n")

#!/usr/bin/env python3
"""Generates apps/pagedesk/pdrenc.h (PAGEDESK-SPEC 11.4): StandardEncoding and
MacRomanEncoding to Windows-1252.  Run from apps/pagedesk/: python3 hosttest/pdr_gen.py"""
std = {0xA1:0xA1,0xA2:0xA2,0xA3:0xA3,0xA5:0xA5,0xA6:0x83,0xA7:0xA7,0xA8:0xA4,0xA9:0x27,0xAA:0x93,0xAB:0xAB,
0xAC:0x8B,0xAD:0x9B,0xB1:0x96,0xB2:0x86,0xB3:0x87,0xB4:0xB7,0xB6:0xB6,0xB7:0x95,0xB8:0x82,0xB9:0x84,0xBA:0x94,
0xBB:0xBB,0xBC:0x85,0xBD:0x89,0xBF:0xBF,0xC1:0x60,0xC2:0xB4,0xC3:0x88,0xC4:0x98,0xC5:0xAF,0xC8:0xA8,0xCB:0xB8,
0xD0:0x97,0xE1:0xC6,0xE3:0xAA,0xE9:0xD8,0xEA:0x8C,0xEB:0xBA,0xF1:0xE6,0xF9:0xF8,0xFA:0x9C,0xFB:0xDF}
std_tab=[std.get(c,0) for c in range(0xA0,0x100)]
mac=[]
for c in range(0x80,0x100):
    ch=bytes([c]).decode('mac_roman')
    try: b=ch.encode('cp1252')[0]
    except Exception: b=0
    mac.append(b)
def fmt(name,t):
    out="static const pdb %s[%d] = {\n"%(name,len(t))
    for i in range(0,len(t),16):
        out+="    "+", ".join("0x%02X"%v for v in t[i:i+16])+",\n"
    return out+"};\n"
open('pdrenc.h','w').write("/* generated by hosttest/pdr_gen.py - StandardEncoding (0xA0..) and MacRomanEncoding\n * (0x80..) to Windows-1252, 0 = no mapping (PAGEDESK-SPEC 11.4) */\n"+fmt('enc_std_hi',std_tab)+fmt('enc_mac_hi',mac))

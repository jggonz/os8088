#!/usr/bin/env python3
"""Generate apps/pagedesk/pdwwid.h: TEMPORARY Core-14 advance widths for the
writer's FreeText wrapping (PAGEDESK-SPEC 20.5.6). Replaced by PDRES's width
tables (PAGEDESK-SPEC 11.3) at integration.

Source: Adobe's Core 14 AFM advance widths (public facts, 1/1000 em), read from
reportlab's _fontdata_widths_* modules (BSD) and mapped to Windows-1252 codes
32..255 through reportlab's WinAnsi glyph-name table. Run with PYTHONPATH
pointing at a reportlab checkout:  tools: python3 pdw_genwidths.py > ../pdwwid.h
Faces emitted: Helvetica, Helvetica-Bold, Times-Roman, Times-Bold, Times-Italic,
Times-BoldItalic (Oblique faces share Helvetica's widths, Courier is 600)."""
import sys
from reportlab.pdfbase import _fontdata_enc_winansi as w
import importlib
faces = [("helv", "helvetica"), ("helvb", "helveticabold"), ("tim", "timesroman"),
         ("timb", "timesbold"), ("timi", "timesitalic"), ("timbi", "timesbolditalic")]
print("/* GENERATED by hosttest/pdw_genwidths.py - TEMPORARY, see PAGEDESK-SPEC 20.5.6 */")
print("/* Core-14 AFM advance widths, 1/1000 em, Windows-1252 codes 32..255 */")
for key, mod in faces:
    m = importlib.import_module("reportlab.pdfbase._fontdata_widths_" + mod)
    vals = []
    for c in range(32, 256):
        g = w.WinAnsiEncoding[c]
        vals.append(m.widths.get(g, m.widths.get("space", 500)) if g else 500)
    print("static const unsigned pdw_w_%s[224] = {" % key)
    for i in range(0, 224, 16):
        print("  " + ",".join("%d" % v for v in vals[i:i + 16]) + ",")
    print("};")

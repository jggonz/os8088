; =============================================================================
; os8088 - apps/midirack/midirack.asm
;
; MIDIRACK.O88 - a MIDI file player (SPEC.md 105). A Standard MIDI File, type
; 0 or 1, read whole into one claim and played through whatever the machine
; has:
;
;   an OPL2 or OPL3 (an AdLib, or a Sound Blaster's own chip) - claimed whole
;       through SOUND.DRV's package verbs (SPEC.md 34.12), 8 or 17 voices of
;       two-operator FM from an original General MIDI bank (mrtab.inc);
;   a Sound Blaster's DSP - a software synth (pulse waves and noise) streamed
;       through an external ring, behind the desktop (SPEC.md 34.5.3);
;   the PC speaker - the same synth through os88spk.inc's pulse width, in a
;       rate bracket like the Audio Player's (SPEC.md 34.11, 86.21); or, with
;       "Play in Background" ticked, ONE square wave on the desktop, the
;       melody, through OSAPI_SND_TONE.
;
; Files (SPEC.md 105.2):
;   midirack.asm  header, icon, the .MID association, all bss, entry, data
;   mrseq.inc     the SMF reader and the sequencer          (prefix mrq_)
;   mrchan.inc    the sixteen channels and the voices       (mrc_, mrv_)
;   mrfm.inc      the FM chip, and the speaker's tone       (mrf_, mrn_)
;   mrsyn.inc     the synth                                  (mry_)
;   mrout.inc     the outputs opened, played, paused, closed; the worker
;                 and the speaker's bracket                  (mro_, mrw_, mrk_)
;   mrlist.inc    the playlist and the file loads           (mrl_)
;   mrui.inc      the window: layout and drawing            (mru_)
;   mrcb.inc      the callbacks, the transport, the cards   (mr_)
;   mrtab.inc     GENERATED by tools/os88midi.py: pitches, levels, names,
;                 the FM bank, the synth's voicing
; =============================================================================


    MRB mr_seqon                    ; the sequencer may run
    MRB mr_ended                    ; the song has played out: the UI's turn
    MRB mr_dry                      ; the load's dry run: no output
    MRB mr_first_paint
    MRB mr_card                     ; the card up: 0 / MR_CARD_*
    MRB mr_arg_pending
    MRBUF mr_arg_name, 16
    MRW mr_arg_dir
    MRB mr_arg_vol
    MRW mr_msg                      ; status line 3
    MRW mr_fseg                     ; the song's claim
    MRW mr_fkb                      ; ...its size in KB
    MRW mr_fsize                    ; the song's bytes
    MRB mr_loaded                   ; a song is in the claim...
    MRB mr_lidx                     ; ...this playlist entry
    MRW mr_lenlo                    ; its length in ms (the dry run)
    MRW mr_lenhi
    MRW mr_meas                     ; its measures
    MRW mr_bpm0                     ; its first tempo, BPM
    MRBUF mr_w, 8                   ; the multi-word scratch (mr_mdiv)
    MRB mr_cpu                      ; CPU_8086 / 286 / 386
    MRB mr_fmkind                   ; 0 none / SND_OPL2 / SND_OPL3 (at entry)
    MRB mr_hassb                    ; SND_CAP_PCM_BG at entry
    MRB mr_sbhi                     ; ...and SND_CAP_PCM_HI: rates past 22 kHz
    MRB mr_rate                     ; the synth's rate: an index into mr_rates,
                                    ; 0 = Automatic (Settings, SPEC.md 105.9.2)
    MRB mr_cfgdirty                 ; a setting moved since MIDIRACK.CFG
    MRBUF mr_snap, 2                ; (scratch)

; =============================================================================
; mr_entry - the loader calls this once (SPEC.md 20.1). The loader shows the
;            window afterwards: no drawing and no worker here.
; =============================================================================
mr_entry:
    call OSAPI_CPU_INFO
    mov [mr_cpu], al
    call OSAPI_SND_CAPS             ; AX = caps
    test ax, SND_CAP_PCM_BG
    jz .nosb
    mov byte [mr_hassb], 1
.nosb:
    test ax, SND_CAP_PCM_HI
    jz .nohi
    mov byte [mr_sbhi], 1
.nohi:
    test ax, SND_CAP_FM
    jz .nofm
    mov al, SND_FM_INFO             ; which chip (claims nothing)
    call OSAPI_SND_FM
    jc .nofm
    mov [mr_fmkind], al
.nofm:
    call mra_load                   ; the colour face's pictures, if colour
    mov byte [mr_levels], 1
    mov byte [mr_want], MR_OUT_AUTO
    call OSAPI_ARG_FILE             ; CF = 1 launched empty
    jc .nodoc
    mov di, mr_arg_name             ; SI -> the name in KERNEL_SEG (ES)
    mov cx, 15
.cpn:
    mov al, [es:si]
    mov [di], al
    inc si
    inc di
    or al, al
    jz .cpd
    loop .cpn
.cpd:
    mov byte [mr_arg_name+15], 0
    mov [mr_arg_dir], dx
    mov [mr_arg_vol], bl
    mov byte [mr_arg_pending], 1
.nodoc:
    call mrl_init
    mov si, mr_tpl
    call OSAPI_WM_CREATE            ; BX = window ptr
    jc .fail
    mov [mr_win], bx
    mov si, mr_prefer               ; a shape for each of the three screens
    call OSAPI_WM_PREFER
    push ax
    push bx
    push si
    push di
    push dx
    mov ax, bx
    mov bx, mru_btrec
    mov si, mr_onup
    mov di, mr_ondrag
    mov dx, mr_onclick              ; OUR click work: the library takes the
    call os88ui_btninit             ; press first and chains here
    pop dx
    pop di
    pop si
    pop bx
    pop ax
    OS88_REGION_MOVABLE
    mov si, mr_menus
    call OSAPI_MENU_SET
    mov si, mr_about
    call OSAPI_ABOUT_SET
    mov ax, mr_onwake
    call OSAPI_WM_ONWAKE
    mov ax, mr_onclose
    call OSAPI_WM_ONCLOSE
    mov word [mr_msg], mr_s_ready
    mov byte [mr_state], MR_ST_STOP
    mov byte [mr_first_paint], 1    ; the settled repaint, and the playlist,
    mov bx, [mr_win]                ; from the first wake (SPEC.md 86.7)
    call OSAPI_WM_WAKE
    clc
    ret
.fail:
    call mra_free                   ; (a claim taken before the window was)
    stc
    ret


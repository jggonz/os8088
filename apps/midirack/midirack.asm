; =============================================================================
; THE TAIL (SPEC.md 105.6.1): read once, by mr_entry's first call, and then
; mrk_pring's first bytes - it must be the image's last, and it must fit the
; page. Even, as every bss word keeps its parity from mr_bss0
; =============================================================================
    align 2, db 0
mr_ztail:
; mrt_unz - mrt_tl, mrt_amp, mrt_fn, mrt_fq and mrt_pow into their bss out of
;           mrt_z, then the FM bank and kit out of mrt_zc's columns (SPEC.md
;           105.6.1). mrt_z: per table a first value and step, then a two-bit code an
;           entry whose value less the bias is the step's change. The step is
;           a BYTE added with a carry into the value's high byte - exact for a
;           word table (steps 0..118) and for a byte table's low byte, whose
;           high is spilled onto the next entry and the next table's first.
;           tools/os88midi.py's unz() is this loop, and refuses a stream it
;           does not read back.
mrt_unz:
    push bp
    cld
    mov si, mrt_z
.tab:
    lodsw
    xchg ax, di                     ; DI = the table (0 ends the list)
    or di, di
    jz .done
    lodsw
    xchg ax, cx                     ; CX = its entries, a multiple of 4
    lodsw
    xchg ax, bx                     ; BX = the first
    lodsw
    xchg ax, dx                     ; DL = the first step, DH = the bias
    lodsb
    cbw
    xchg ax, bp                     ; BP = 1 or 2, the entry's bytes
.el:
    mov [di], bx
    add di, bp
    test cl, 3
    jnz .have
    lodsb                           ; four codes a byte, the low pair first
    mov ah, al
.have:
    mov al, ah
    and al, 3
    shr ah, 1
    shr ah, 1
    sub al, dh
    add dl, al                      ; the step moves
    add bl, dl                      ; ...and the value by it
    adc bh, 0
    loop .el
    jmp short .tab
.done:                              ; SI = mrt_zc, which MRT_ZTAIL puts right
.col:                               ; after the stream's end: the FM bank's
    lodsw                           ; columns, each byte the bss's own plus
    xchg ax, di                     ; the one BX before it (BX = 0: itself,
    or di, di                       ; still zero)
    jz .ret
    lodsw
    xchg ax, cx                     ; CL = the count, CH = the stride
    lodsb
    cbw
    xchg ax, bx
    mov al, ch
    cbw
    xchg ax, dx
    xor ch, ch
.b:
    lodsb
    add al, [di+bx]
    mov [di], al
    add di, dx
    loop .b
    jmp short .col
.ret:
    pop bp
    ret
    MRT_ZTAIL

; -----------------------------------------------------------------------------
; mra_load - the colour face's pictures, part 0 of this file, into a claim of
; their own (SPEC.md 105.9.5). Only on a COLOUR PRIMARY: a Hercules or a CGA
; machine never reads it. Silent when the heap is short or the read fails -
; the transport is then code-drawn, which is a complete face and not a broken
; one. UI task, at entry only, so it lives in the tail (a read and a claim,
; SPEC.md 20.6 rule 7). OP_SELF's read (SPEC.md 20.12.9.1): the packed stream
; at the part's own SECTOR - READ_AT's unit on kern_big (SPEC.md 18.4.4.2),
; and kern_small draws no colour - R up the claim, expanded down onto its
; base (SPEC.md 20.12.7.4, the standard's arithmetic). The claim is
; STATE-major - the five up faces, the five pressed, the five greyed - so the
; part's up faces land where they stay, and it is MOVABLE (mra_reloc)
; -----------------------------------------------------------------------------
mra_load:
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    push es
    call OSAPI_VIDEO                ; DH = the primary's bits per pixel
    cmp dh, 1
    jbe .out
    mov si, op_table + OP_T_ROWS    ; SI = part 0's row
    mov cx, [si+OP_R_ZKB]           ; CX = its packed bytes
    mov bx, [si+OP_R_LEN]           ; BX = what they expand to: the derive's
    cmp bx, MRA_FSIZE               ; input, or a package packed wrong
    jne .out
    sub bx, cx                      ; BX = R = roundup512(len - packed): where
    jbe .out                        ; the stream is read, a sector boundary
    add bx, 511                     ; up the claim (a disk-visible base is
    and bx, ~511                    ; 512-aligned)
    mov ax, [si+OP_R_OFF]           ; DX:AX = the part's byte offset
    mov dx, ax
    push cx
    mov cl, 9
    shl ax, cl
    mov cl, 7
    shr dx, cl
    pop cx
    push ax
    push dx
    mov ax, MRA_CLAIM / 1024
    call OSAPI_MEM_CLAIM            ; DX = the segment
    mov bp, dx
    pop dx
    pop ax
    jc .out
    mov es, bp
    push cx                         ; (the packed bytes, for the decoder)
    add cx, 511
    and cx, ~511                    ; CX = the capacity: whole sectors, the
    mov si, op_name                 ; file ending inside the last one
    call OSAPI_FILE_READ_AT         ; DX:AX = the bytes delivered
    pop cx
    jc .free
    cmp ax, cx
    jb .free
    push ds
    mov al, [op_table + OP_T_FMT]   ; (ours: DS is the stream's a line on)
    xor ah, ah
    mov dx, MRA_FSIZE
    mov si, bx
    mov ds, bp                      ; DS:SI = the stream, ES:0 its output
    xor di, di
    xor bx, bx
    call OSAPI_DECOMP
    jc .zbad
    call mra_derive                 ; DS = ES = the claim, and BP spent
    mov dx, es
    pop ds
    mov [mra_seg], dx
    mov ax, mra_reloc               ; nothing points into it but mra_seg
    call OSAPI_MEM_MOVABLE
    jmp short .out
.zbad:
    pop ds
.free:
    mov dx, bp
    call OSAPI_MEM_FREE
.out:
    pop es
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret

; mra_derive - the ten faces the file does not carry, each button's pressed
; and greyed from its up face. DS = ES = the claim; clobbers all but those.
; The recipe first, out of the way of the pressed faces it lies under
mra_derive:
    mov si, MRA_NB * MRA_FACE
    mov di, MRA_REC
    mov cx, MRA_FSIZE - MRA_NB * MRA_FACE
    rep movsb
    xor bx, bx                      ; BX = the button's up face
.b:
    call mra_press
    call mra_grey
    add bx, MRA_FACE
    cmp bx, MRA_NB * MRA_FACE
    jb .b
    ret

; mra_press - BX = an up face: its pressed one, MRA_NB faces on
; (the generator's derive_pressed)
mra_press:
    push bx
    mov ax, MRA_REC                 ; AX = the plane's frame rows
    mov dx, MRA_FIX                 ; DX = its two fixed bytes
.pl:
    mov si, bx                      ; the first row and the last: the up
    lea di, [bx + MRA_PFACE]        ; face's
    movsw
    movsw
    movsw
    lea si, [bx + (MRA_H - 1) * MRA_ROW]
    lea di, [bx + MRA_PFACE + (MRA_H - 1) * MRA_ROW]
    movsw
    movsw
    movsw
    mov si, ax                      ; the frame's own rows
    lea di, [bx + MRA_PFACE + MRA_PR1 * MRA_ROW]
    mov cx, MRA_ROW                 ; (PR1 and PR2: two rows, six words)
    rep movsw
    lea di, [bx + MRA_PFACE + MRA_PR3 * MRA_ROW]
    movsw
    movsw
    movsw
    push si                         ; (the next plane's rows)
    push dx
    mov si, dx
    lodsw
    xchg ax, bp                     ; BP = the fixed bytes' pixels
    lea si, [bx + (MRA_SH0 - 1) * MRA_ROW]
    lea di, [bx + MRA_PFACE + MRA_SH0 * MRA_ROW]
    mov dx, MRA_SH1 - MRA_SH0
.row:
    clc                             ; the row above, a pixel right, a zero
%rep MRA_ROW                        ; in at the left
    lodsb
    rcr al, 1
    stosb
%endrep
    mov cx, bp
    and byte [di - MRA_ROW], MRA_A0
    or [di - MRA_ROW], cl
    and byte [di - 1], MRA_A5
    or [di - 1], ch
    dec dx
    jnz .row
    pop dx
    pop ax
    add bx, MRA_PL
    inc dx
    inc dx
    cmp dx, MRA_FIX + 4 * 2
    jb .pl
    pop bx
    ret

; mra_grey - BX = an up face: its greyed one, 2 x MRA_NB faces on (the
; generator's derive_greyed)
mra_grey:
    push bx
    mov dx, 4                       ; rows 0, 1, H-2 and H-1 of each plane:
    mov si, bx                      ; the up face's
.c:
    lea di, [si + MRA_GFACE]
    mov cx, MRA_ROW
    rep movsw
    add si, (MRA_H - 4) * MRA_ROW
    lea di, [si + MRA_GFACE]
    mov cx, MRA_ROW
    rep movsw
    dec dx
    jnz .c
    mov di, MRA_KP                  ; no shape above the first row
    xor ax, ax
    stosw
    stosw
    stosw
    add bx, MRA_G0 * MRA_ROW        ; BX = the row, in plane 0 of the up face
    mov word [MRA_Y], MRA_G0
.row:
    mov si, MRA_KP                  ; the shadow: the row above's shape, a
    mov di, MRA_WR                  ; pixel right (before this row's
    clc                             ; replaces it)
%rep MRA_ROW
    lodsb
    rcr al, 1
    stosb
%endrep
    xor ax, ax                      ; the wipe's own mask: all of the rect,
    cmp word [MRA_Y], MRA_G1        ; or on G1 none of it
    jae .r
    dec ax
.r:
    mov [MRA_WF], ax
    xor di, di                      ; DI = the word
.k:
    mov ax, [bx + di]
    mov dx, [bx + di + MRA_PL]
    mov cx, [bx + di + 2 * MRA_PL]
    mov si, [bx + di + 3 * MRA_PL]
    mov bp, ax
    or bp, dx
    or bp, cx
    or bp, si                       ; BP = any colour but black
    and ax, dx
    and ax, cx
    not si
    and ax, si                      ; AX = the face's grey
    not ax
    and ax, bp                      ; AX = coloured (the icon)
    cmp word [MRA_Y], MRA_GB
    jb .ka
    mov ax, bp                      ; ...or from GB, black (the label)
    not ax
.ka:
    mov dx, [di + MRA_RM]
    and dx, [MRA_WF]                ; DX = the wipe
    and ax, dx                      ; AX = the shape
    mov [di + MRA_KP], ax
    mov cx, [di + MRA_WR]           ; CX = the shadow
    mov si, cx
    or si, ax
    mov [di + MRA_WK], si
    or cx, dx
    mov [di + MRA_T], cx
    not dx
    mov [di + MRA_NR], dx
    not ax
    mov [di + MRA_NK], ax
    inc di
    inc di
    cmp di, MRA_ROW
    jb .k
    mov si, bx                      ; the four planes: three that wipe to
    lea di, [bx + MRA_GFACE]        ; grey and lose the shape, the fourth
    mov dx, 3                       ; that the shadow and the shape set
.p:
%assign MRA_J 0
%rep MRA_ROW / 2
    lodsw
    or ax, [MRA_T + MRA_J]
    and ax, [MRA_NK + MRA_J]
    stosw
%assign MRA_J MRA_J + 2
%endrep
    add si, MRA_PL - MRA_ROW
    add di, MRA_PL - MRA_ROW
    dec dx
    jnz .p
%assign MRA_J 0
%rep MRA_ROW / 2
    lodsw
    and ax, [MRA_NR + MRA_J]
    or ax, [MRA_WK + MRA_J]
    stosw
%assign MRA_J MRA_J + 2
%endrep
    add bx, MRA_ROW
    inc word [MRA_Y]
    cmp word [MRA_Y], MRA_G1
    jbe .row
    pop bx
    ret
; THE PART TABLE (SPEC.md 20.12.3), and the standard's code after it - both in
; the tail, because only mr_entry reads either: one row, nothing in a carve,
; so op_load is the name copy (SPEC.md 20.12.9.3)
OS88_PARTS_BEGIN 1
    OS88_PART OP_ASSET, OP_LAZY | OP_COMP | OP_SELF     ; 0  the faces
OS88_PARTS_END
    align 2, db 0                   ; (an even image, as it always was)
%if mra_load - mrt_z < OP_BSS
  %error "op_load's bss is laid over mrt_z, which mrt_unz has spent by then: it must fit"
%endif
%if ($ - mr_ztail) > OS88SPK_PRL + MRL_MAX * MRL_ENT
  %error "the image's tail has outgrown mrk_pring and mrl_ent, laid over it"
%endif
    OS88_BSS mr_bss0 + MR_BSS - os88_image_end
    OS88_IMAGE_END

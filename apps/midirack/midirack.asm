; =============================================================================
; mr_entry - the loader calls this once (SPEC.md 20.1). The loader shows the
;            window afterwards: no drawing and no worker here.
; =============================================================================
mr_entry:
    push si                         ; the kernel's name for this file
    call mrt_unz                    ; the smooth tables, first (105.6.1) -
    pop si                          ; their spent stream is op_load's bss
    push es                         ; op_load spends ES, and OSAPI_ARG_FILE
    call op_load                    ; below reads through KERNEL_SEG's. The
    pop es                          ; one row is lazy: a name copy, CF = 0
    call OSAPI_CPU_INFO
    mov [mr_cpu], al
    call OSAPI_SND_CAPS             ; AX = caps
    test ax, SND_CAP_PCM_BG
    jz .nosb
    mov byte [mr_hassb], 1
.nosb:
    test ax, SND_CAP_PCM_HI
    jz .nohi
    mov byte [mr_sbhi], 1
.nohi:
    test ax, SND_CAP_FM
    jz .nofm
    mov al, SND_FM_INFO             ; which chip (claims nothing)
    call OSAPI_SND_FM
    jc .nofm
    mov [mr_fmkind], al
.nofm:
    call mrm_info                   ; an MPU-401 behind SOUND.DRV?
    call mwt_info                   ; ...and a wavetable bank beside us?
    call mr_lptinfo                 ; ...and a Covox the user announced?
    call mra_load                   ; the colour face's pictures, if colour
    mov byte [mr_levels], 1
    mov byte [mr_want], MR_OUT_AUTO
    call OSAPI_ARG_FILE             ; CF = 1 launched empty
    jc .nodoc
    mov di, mr_arg_name             ; SI -> the name in KERNEL_SEG (ES)
    mov cx, 15
.cpn:
    mov al, [es:si]
    mov [di], al
    inc si
    inc di
    or al, al
    jz .cpd
    loop .cpn
.cpd:
    mov byte [mr_arg_name+15], 0
    mov [mr_arg_dir], dx
    mov [mr_arg_vol], bl
    mov byte [mr_arg_pending], 1
.nodoc:
    call mrl_init
    mov si, mr_tpl
    call OSAPI_WM_CREATE            ; BX = window ptr
    jc .fail
    mov [mr_win], bx
    mov si, mr_prefer               ; a shape for each of the three screens
    call OSAPI_WM_PREFER
    push bx                         ; (btninit keeps every register; the
    xchg ax, bx                     ; window is all the rest of us reads)
    mov bx, mru_btrec
    mov si, mr_onup
    mov di, mr_ondrag
    mov dx, mr_onclick              ; OUR click work: the library takes the
    call os88ui_btninit             ; press first and chains here
    pop bx
    OS88_REGION_MOVABLE mr_nop      ; (a bare ret: nothing points inside us)
    mov si, mr_menus
    call OSAPI_MENU_SET
    mov si, mr_about
    call OSAPI_ABOUT_SET
    mov ax, mr_onwake
    call OSAPI_WM_ONWAKE
    mov ax, mr_onclose
    call OSAPI_WM_ONCLOSE
    mov ax, mr_onwheel              ; the WHEEL scrolls the playlist
    call OSAPI_WM_ONWHEEL           ; (SPEC.md 13.18)
    mov word [mr_msg], mr_s_ready
    mov byte [mr_state], MR_ST_STOP
    mov byte [mr_first_paint], 1    ; the settled repaint, and the playlist,
    mov bx, [mr_win]                ; from the first wake (SPEC.md 86.7)
    call OSAPI_WM_WAKE
    clc
    ret
.fail:
    call mra_free                   ; (a claim taken before the window was)
    stc
    ret


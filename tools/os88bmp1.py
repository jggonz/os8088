#!/usr/bin/env python3
"""Convert the Browser's fixed 1bpp BMP icons to native BLIT1 bands."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "apps" / "browser" / "assets"
ICONS = (
    ("br_dl_icon_server", "server_48x48_1bpp.bmp", 48, 48),
    ("br_dl_icon_document", "document_24x28_1bpp.bmp", 24, 28),
    ("br_dl_icon_pc", "pc_48x48_1bpp.bmp", 48, 48),
)


def bmp_band(path: Path, want_w: int, want_h: int) -> bytes:
    data = path.read_bytes()
    if len(data) < 62 or data[:2] != b"BM":
        raise ValueError(f"{path}: not a complete 1bpp Windows BMP")

    pixel_offset = struct.unpack_from("<I", data, 10)[0]
    dib_size = struct.unpack_from("<I", data, 14)[0]
    width, signed_height, planes, bpp = struct.unpack_from("<iiHH", data, 18)
    compression = struct.unpack_from("<I", data, 30)[0]
    colors_used = struct.unpack_from("<I", data, 46)[0]
    if (dib_size, width, abs(signed_height), planes, bpp, compression) != (
        40,
        want_w,
        want_h,
        1,
        1,
        0,
    ):
        raise ValueError(
            f"{path}: expected uncompressed {want_w}x{want_h} 1bpp BMP"
        )
    if colors_used not in (0, 2) or pixel_offset < 62:
        raise ValueError(f"{path}: expected a two-entry BMP palette")

    # BMP palette entries are B,G,R,reserved. Index zero is black and index
    # one white. Preserve the palette-index bits: set pixels are white and
    # clear pixels black, which also matches 1bpp adapters' lit-pixel rule.
    if data[54:62] != bytes((0, 0, 0, 0, 255, 255, 255, 0)):
        raise ValueError(f"{path}: palette must be black then white")

    row_bytes = (want_w + 7) // 8
    bmp_stride = ((want_w + 31) // 32) * 4
    if pixel_offset + bmp_stride * want_h > len(data):
        raise ValueError(f"{path}: truncated pixel array")

    rows = []
    for y in range(want_h):
        file_y = want_h - 1 - y if signed_height > 0 else y
        start = pixel_offset + file_y * bmp_stride
        rows.append(data[start : start + row_bytes])
    return b"".join(rows)


def render() -> str:
    lines = [
        "; Generated by tools/os88bmp1.py from apps/browser/assets.",
        "; Row-major BLIT1 bands: bit 7 leftmost, set bits are white paper.",
        "",
    ]
    for label, filename, width, height in ICONS:
        band = bmp_band(ASSETS / filename, width, height)
        stride = width // 8
        lines.append(f"{label}:")
        lines.append(f"    ; {width}x{height}, {stride} bytes per row.")
        for at in range(0, len(band), 8):
            lines.append("    db " + ",".join(f"0{byte:02X}h" for byte in band[at : at + 8]))
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path, help="generated NASM include")
    args = parser.parse_args()
    output = render()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="ascii", newline="\n") as stream:
        stream.write(output)


if __name__ == "__main__":
    main()

"""ISO 11172-3 / 13818-3 Layer III constant tables for XTMP3 (SPEC.md 121).

Literal data only: tools/x3sim.py (the reference decoder) and tools/x3tables.py
(the target table generator) both read these, so a table is written down once.

PROVENANCE.  The values are the standard's.  They were transcribed by
machine, not typed, from two independently written public-domain decoders,
used as references only and never committed:

  minimp3  https://github.com/lieff/minimp3  commit ea99364f61c14656440e8d77e9c233ccf3124633
           CC0 1.0 (public domain dedication)
  PDMP3    https://github.com/technosaurus/PDMP3  commit 2a206a3ada78ec4d13434847f05f50097c60c36a
           public domain (Krister Lagerstrom's thesis decoder: "My work is placed
           in the public domain")

The Huffman codebooks were walked out of PDMP3's ISO dist10-style trees and
every codeword was then decoded through minimp3's (entirely differently
packed) lookup tables: all 1,474 codewords of all 17 trees agree on value and
length, every tree is a complete prefix code (Kraft sum exactly 1) and every
value appears once.  The synthesis window D[] is PDMP3's, and every entry is
an exact multiple of 2^-16, as the standard prints it; it is kept here as
the integer D * 65536.  The scalefactor-band widths, the MPEG-2 partition
table and the slen decode are minimp3's, which agree with mpglib (the decoder
`lame --decode` uses, the comparison reference) including the MPEG-2.5 8 kHz
table that ISO does not define.
"""


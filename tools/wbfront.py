#!/usr/bin/env python3
"""WireBall splash: deterministic EGA 4bpp and Bayer 1bpp from the source art.

The 1bpp form ships as a residual against the 1bpp picture the 4bpp one
predicts (a dither level per colour against the same Bayer matrix); the
package rebuilds it on its first monochrome paint.

No image-generation dependency at build time. The source and prompt are
committed; only pixel conversion runs here. --check refuses a stale include.
"""
from pathlib import Path
import argparse
from PIL import Image
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import os88lz

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'apps/wireball/art/splash-source.png'
OUT = ROOT / 'apps/wireball/art/wbfront.inc'
WIDTH, HEIGHT = 416, 104
EGA = [(0,0,0),(0,0,170),(0,170,0),(0,170,170),(170,0,0),(170,0,170),
       (170,85,0),(170,170,170),(85,85,85),(85,85,255),(85,255,85),
       (85,255,255),(255,85,85),(255,85,255),(255,255,85),(255,255,255)]
BAYER = ((0,8,2,10),(12,4,14,6),(3,11,1,9),(15,7,13,5))


def emit(label, data):
    lines = [label + ':']
    for i in range(0, len(data), 24):
        lines.append('    db ' + ','.join('0x%02x' % b for b in data[i:i+24]))
    return '\n'.join(lines)


def levels(indexed, mono):
    """Per colour, the dither level (0..16, a pixel lights when level > its
    Bayer cell) that agrees with the most monochrome pixels of that colour."""
    best = [0] * 16
    for c in set(indexed):
        errors = [0] * 17
        for y in range(HEIGHT):
            for x in range(WIDTH):
                if indexed[y*WIDTH+x] != c:
                    continue
                bit = mono[y*(WIDTH//8)+x//8] >> (7 - (x & 7)) & 1
                for level in range(17):
                    errors[level] += (level > BAYER[y & 3][x & 3]) != bit
        best[c] = min(range(17), key=lambda level: errors[level])
    return best


def predict(packed, level):
    """The 1bpp picture the colour picture predicts - what wb_monobuild
    computes on the machine before it XORs the shipped residual in."""
    out = bytearray(WIDTH*HEIGHT//8)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            byte = packed[(y*WIDTH+x)//2]
            c = byte >> 4 if not x & 1 else byte & 15
            if level[c] > BAYER[y & 3][x & 3]:
                out[y*(WIDTH//8)+x//8] |= 0x80 >> (x & 7)
    return out


def convert():
    source = Image.open(SOURCE).convert('RGB')
    if source.size != (2079, 756):
        raise ValueError('source dimensions changed; update the documented crop deliberately')
    image = source.crop((0, 96, 2079, 616)).resize((WIDTH, HEIGHT), Image.NEAREST)
    rgb = list(image.getdata())
    colors = {}
    for p in set(rgb):
        colors[p] = min(range(16), key=lambda i: sum((p[c]-EGA[i][c])**2 for c in range(3)))
    indexed = [colors[p] for p in rgb]
    packed = bytes((indexed[i] << 4) | indexed[i+1] for i in range(0, len(indexed), 2))
    mono = bytearray(WIDTH*HEIGHT//8)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            p = rgb[y*WIDTH+x]
            luminance = (p[0]*3 + p[1]*6 + p[2])//10
            if luminance > (BAYER[y & 3][x & 3]*16 + 8):
                mono[y*(WIDTH//8)+x//8] |= 0x80 >> (x & 7)
    # The 1bpp picture ships as its difference from what the colour picture
    # predicts, which is mostly zero and packs to about half (SPEC.md 109.4).
    level = levels(indexed, mono)
    residual = bytes(a ^ b for a, b in zip(predict(packed, level), mono))
    # ...then nudge each level while the residual packs smaller under the
    # package's own LZ4 (SPEC.md 20.13). Deterministic: a fixed visiting order.
    size = len(os88lz.compress(residual, os88lz.LZ4))
    better = True
    while better:
        better = False
        for c in sorted(set(indexed)):
            for step in (-2, -1, 1, 2):
                trial = list(level)
                trial[c] += step
                if not 0 <= trial[c] <= 16:
                    continue
                r = bytes(a ^ b for a, b in zip(predict(packed, trial), mono))
                n = len(os88lz.compress(r, os88lz.LZ4))
                if n < size:
                    level, residual, size, better = trial, r, n, True
    if bytes(a ^ b for a, b in zip(predict(packed, level), residual)) != mono:
        raise SystemExit('internal: the residual does not rebuild the 1bpp picture')
    text = ('; GENERATED by tools/wbfront.py; source and prompt beside this file.\n'
            'WB_ART_W equ %d\nWB_ART_H equ %d\n' % (WIDTH, HEIGHT))
    text += emit('wb_artcolor', packed) + '\n'
    text += emit('wb_artlevel', bytes(level)) + '\n'
    text += emit('wb_artbayer', bytes(v for row in BAYER for v in row)) + '\n'
    text += emit('wb_artmono', residual) + '\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = convert()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit('WireBall artwork is stale: run python3 tools/wbfront.py')
        print('WireBall artwork is current (416x104, 21632 color + 5408 mono residual bytes)')
    else:
        OUT.write_text(text)
        print('Wrote ' + str(OUT))

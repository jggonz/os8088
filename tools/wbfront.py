#!/usr/bin/env python3
"""WireBall splash: deterministic EGA 4bpp and Bayer 1bpp from the source art.

No image-generation dependency at build time. The source and prompt are
committed; only pixel conversion runs here. --check refuses a stale include.
"""
from pathlib import Path
import argparse
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'apps/wireball/art/splash-source.png'
OUT = ROOT / 'apps/wireball/art/wbfront.inc'
WIDTH, HEIGHT = 416, 104
EGA = [(0,0,0),(0,0,170),(0,170,0),(0,170,170),(170,0,0),(170,0,170),
       (170,85,0),(170,170,170),(85,85,85),(85,85,255),(85,255,85),
       (85,255,255),(255,85,85),(255,85,255),(255,255,85),(255,255,255)]
BAYER = ((0,8,2,10),(12,4,14,6),(3,11,1,9),(15,7,13,5))


def emit(label, data):
    lines = [label + ':']
    for i in range(0, len(data), 24):
        lines.append('    db ' + ','.join('0x%02x' % b for b in data[i:i+24]))
    return '\n'.join(lines)


def convert():
    source = Image.open(SOURCE).convert('RGB')
    if source.size != (2079, 756):
        raise ValueError('source dimensions changed; update the documented crop deliberately')
    image = source.crop((0, 96, 2079, 616)).resize((WIDTH, HEIGHT), Image.NEAREST)
    rgb = list(image.getdata())
    colors = {}
    for p in set(rgb):
        colors[p] = min(range(16), key=lambda i: sum((p[c]-EGA[i][c])**2 for c in range(3)))
    indexed = [colors[p] for p in rgb]
    packed = bytes((indexed[i] << 4) | indexed[i+1] for i in range(0, len(indexed), 2))
    mono = bytearray(WIDTH*HEIGHT//8)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            p = rgb[y*WIDTH+x]
            luminance = (p[0]*3 + p[1]*6 + p[2])//10
            if luminance > (BAYER[y & 3][x & 3]*16 + 8):
                mono[y*(WIDTH//8)+x//8] |= 0x80 >> (x & 7)
    text = ('; GENERATED by tools/wbfront.py; source and prompt beside this file.\n'
            'WB_ART_W equ %d\nWB_ART_H equ %d\n' % (WIDTH, HEIGHT))
    text += emit('wb_artcolor', packed) + '\n' + emit('wb_artmono', mono) + '\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = convert()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit('WireBall artwork is stale: run python3 tools/wbfront.py')
        print('WireBall artwork is current (416x104, 21632 color + 5408 mono bytes)')
    else:
        OUT.write_text(text)
        print('Wrote ' + str(OUT))

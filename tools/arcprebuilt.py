#!/usr/bin/env python3
# =============================================================================
# os8088 - tools/arcprebuilt.py - ARCADE's COMMITTED build state
# (docs/ARCADE-SPEC.md 1.6)
#
#     python3 tools/arcprebuilt.py write  BUILD/arcade apps/arcade/prebuilt
#     python3 tools/arcprebuilt.py stamp  apps/arcade/prebuilt      (the gate)
#     python3 tools/arcprebuilt.py compare BUILD/arcade apps/arcade/prebuilt
#
# ARCADE's translated boards ship as RECIPES - their code with the ROM's
# bytes left as holes - and AUX parts (the PC tables), Q*bert's patch table
# and the import's set table: no ROM byte in any of them (ARCADE-SPEC 1.4,
# 3.10). They are MADE from the ROMs, which tools/getarcrom.py fetches at
# pins from archive.org - and no `make`, and no release, may need archive.org.
# So the last state of them is committed, gzipped, in apps/arcade/prebuilt/,
# and `make arcade` builds the package from it; `make arcadeprebuilt` makes
# them again from the ROMs and writes them here.
#
#   write    the parts, gzipped with no timestamp (the same bytes every
#            time), and STAMP: the SHA-256 of every file that makes them
#   stamp    STAMP against those files as they are now: the fast-tier gate
#            that fails `make` when the translator moved and the committed
#            parts did not (refresh them where the ROMs are: arcadeprebuilt)
#   compare  freshly made parts against the committed ones, byte for byte,
#            and none holding a run of 8 bytes of any pinned ROM (the row
#            arcprebuilt, where the ROMs are)
# =============================================================================
import gzip
import hashlib
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

PARTS = ['invcode.rcp', 'invaux.bin', 'pt2code.rcp', 'pt2aux.bin',
         'lrcode.rcp', 'lraux.bin', 'gfcode.rcp', 'gfaux.bin',
         'swcode.rcp', 'swaux.bin', 'paccode.rcp', 'pacaux.bin',
         'qbpatch.inc', 'arcsets.inc']
# every file whose change can change a part (the ROMs aside: they are pinned)
INPUTS = ['apps/arcade/arcaot.py', 'apps/arcade/arcz80t.py', 'apps/arcade/z80dec.py',
          'apps/arcade/arcrt.inc', 'apps/arcade/arcz80rt.inc', 'apps/arcade/arcdefs.inc',
          'apps/arcade/invaders.seeds', 'apps/arcade/invadpt2.seeds',
          'apps/arcade/lrescue.seeds', 'apps/arcade/gunfight.seeds',
          'apps/arcade/seawolf.seeds', 'apps/arcade/pacman.seeds',
          'apps/arcade/qbert.patch', 'apps/arcade/arcqbgfx.py', 'tools/getarcrom.py']
ROMS = {'inv': 'INVADERS', 'pt2': 'INVADPT2', 'lr': 'LRESCUE', 'gf': 'GUNFIGHT',
        'sw': 'SEAWOLF', 'pac': 'PACMAN'}


def die(msg):
    sys.stderr.write('arcprebuilt: %s\n' % msg)
    sys.exit(1)


def stamp_text():
    lines = ['# GENERATED by tools/arcprebuilt.py write: the inputs these parts were',
             '# made from. `make` checks it (tests/unit/t_arcprebuilt.py).']
    for f in INPUTS:
        lines.append('%s  %s' % (hashlib.sha256(open(os.path.join(ROOT, f), 'rb').read())
                                 .hexdigest(), f))
    return '\n'.join(lines) + '\n'


def gz(data):
    b = io.BytesIO()
    with gzip.GzipFile(fileobj=b, mode='wb', compresslevel=9, mtime=0, filename='') as g:
        g.write(data)
    return b.getvalue()


def write(src, dst):
    os.makedirs(dst, exist_ok=True)
    for p in PARTS:
        d = open(os.path.join(src, p), 'rb').read()
        open(os.path.join(dst, p + '.gz'), 'wb').write(gz(d))
    open(os.path.join(dst, 'STAMP'), 'w').write(stamp_text())
    print('arcprebuilt: %d parts and STAMP written to %s' % (len(PARTS), dst))


def stamp(dst):
    want = open(os.path.join(dst, 'STAMP')).read()
    if want != stamp_text():
        old = dict(reversed(l.split('  ')) for l in want.splitlines() if l and l[0] != '#')
        now = dict(reversed(l.split('  ')) for l in stamp_text().splitlines() if l and l[0] != '#')
        moved = [f for f in INPUTS if old.get(f) != now.get(f)]
        die('%s moved since apps/arcade/prebuilt/ was made: run `make arcadeprebuilt` '
            '(it fetches the pinned ROMs) and commit the parts' % ', '.join(moved))
    print('arcprebuilt: the committed parts are the inputs\' (%d files)' % len(INPUTS))


def compare(src, dst):
    bad = []
    for p in PARTS:
        mine = open(os.path.join(src, p), 'rb').read()
        ref = gzip.open(os.path.join(dst, p + '.gz')).read()
        if mine != ref:
            bad.append('%s differs from the committed one' % p)
    for k, r in ROMS.items():
        rom = open(os.path.join(ROOT, 'build', 'arcade-rom', r + '.ROM'), 'rb').read()
        grams = set(rom[i:i + 8] for i in range(len(rom) - 7) if len(set(rom[i:i + 8])) > 2)
        for p in ('%scode.rcp' % k, '%saux.bin' % k):
            d = gzip.open(os.path.join(dst, p + '.gz')).read()
            hits = sum(1 for i in range(len(d) - 7) if d[i:i + 8] in grams)
            if hits:
                bad.append('%s holds %d runs of 8 of %s\'s bytes' % (p, hits, r))
    for b in bad:
        print('arcprebuilt: FAIL - ' + b)
    if bad:
        return 1
    print('arcprebuilt: %d parts made from the pinned ROMs are the committed ones, and '
          'none holds 8 bytes of a ROM' % len(PARTS))
    return 0


def main():
    if len(sys.argv) < 3:
        die('usage: arcprebuilt.py write SRC DST | stamp DST | compare SRC DST')
    op = sys.argv[1]
    if op == 'write':
        write(sys.argv[2], sys.argv[3])
    elif op == 'stamp':
        stamp(sys.argv[2])
    elif op == 'compare':
        return compare(sys.argv[2], sys.argv[3])
    else:
        die('no %s' % op)
    return 0


if __name__ == '__main__':
    sys.exit(main())

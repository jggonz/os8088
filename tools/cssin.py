#!/usr/bin/env python3
"""Clear Skies' sine table, as the 2-bit SECOND DIFFERENCES it is built from
at launch (SPEC.md 88.5.9.1).

    python3 tools/cssin.py              rewrite apps/skies/cssin.inc
    python3 tools/cssin.py --check      exit 1 if the checked-in file differs

The table is sin(a) x 32768, clamped to 32767, for a in 0..256 of a quarter
turn - 257 words, 514 bytes, and to LZ4 514 bytes of noise: a slowly falling
curve has no repeats. Its first difference falls from 201 to 0 and its second
difference is -3..+1, so the curve is two words and 256 two-bit codes. The
include lays the codes at the TAIL of the table's own 514 bytes behind 450
zeros (which pack to nothing), and `cs_entry` expands them forwards, in place,
before anything reads the table (apps/skies/cs3d.inc, `cs_sininit`): the
writer starts at the head and is never ahead of the reader (asserted below),
so the table costs no scratch and no RAM.

Code c is dd = c - 2, so -2..+1; the one -3 in the whole curve (between
entries 253 and 255, rounding and not the clamp) is a code 0 plus a fix-up the
decoder makes at that one step. The pad code after the last real difference
is 2, a zero.

The decode is SIMULATED here, step for step as cs_sininit does it - including
reading a code byte from the very buffer it is writing - and the result must
be the formula's 257 words exactly, or nothing is written.
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "apps", "skies", "cssin.inc")
N = 257                         # entries: a quarter turn and sin 90
SIZE = 2 * N                    # the table's bytes
NCODE = 64                      # 256 two-bit codes: 255 differences and a pad
PK = SIZE - NCODE               # where the codes begin inside the table


def table():
    return [min(32767, int(round(math.sin(k * 2 * math.pi / 1024) * 32768)))
            for k in range(N)]


def encode(t):
    d = [t[i + 1] - t[i] for i in range(N - 1)]
    dd = [d[i + 1] - d[i] for i in range(N - 2)] + [0]
    fix = [i for i, x in enumerate(dd) if x == -3]
    bad = [(i, x) for i, x in enumerate(dd) if not -3 <= x <= 1]
    if bad or len(fix) != 1:
        sys.exit("cssin: the second differences are not -2..+1 with ONE -3 "
                 "(%s, -3 at %s) - the decoder's alphabet no longer fits"
                 % (bad[:4], fix))
    codes = [max(x, -2) + 2 for x in dd]
    pk = bytearray(NCODE)
    for i, c in enumerate(codes):
        pk[i // 4] |= c << (2 * (i % 4))
    # the decoder's counter is CX = 256 - i, and it tests CL
    return d[0], 256 - fix[0], bytes(pk)


def simulate(d0, fixcl, pk):
    """cs_sininit, byte for byte, in the table's own 514 bytes."""
    m = bytearray(PK) + pk
    di, si, ax, dx, bl = 0, PK, 0, d0, 0
    for cx in range(256, 0, -1):
        m[di] = ax & 255
        m[di + 1] = ax >> 8
        di += 2                                 # stosw
        ax = (ax + dx) & 0xFFFF                 # add ax, dx
        if not cx & 3:                          # test cl, 3 / jnz
            if si <= di - 1:
                sys.exit("cssin: the writer overtook the codes at byte %d" % si)
            bl = m[si]
            si += 1
        dx = (dx + (bl & 3) - 2) & 0xFF         # add dl, bh / sub dl, 2
        bl >>= 2
        if cx & 255 == fixcl:
            dx = (dx - 1) & 0xFF                # the one -3
    m[di] = ax & 255
    m[di + 1] = ax >> 8                         # sin 90
    return [m[2 * k] | m[2 * k + 1] << 8 for k in range(N)]


def render():
    t = table()
    d0, fixcl, pk = encode(t)
    if simulate(d0, fixcl, pk) != t:
        sys.exit("cssin: the simulated decode is not the table")
    out = [
        "; sin(a) x 32768 (clamped to 32767) for a in 0..256 - a QUARTER of the turn,",
        "; which is all cs_sin needs (SPEC.md 88.5.9): the other three quadrants are",
        "; this one reflected and negated.",
        ";",
        "; GENERATED by tools/cssin.py - do not edit by hand; tests/unit/t_cssin.py",
        "; holds it to the generator. THE TABLE SHIPS AS ITS SECOND DIFFERENCES",
        "; (SPEC.md 88.5.9.1): 514 bytes, of which the first CS_SINPK are zeros and",
        "; the last 64 are 256 two-bit codes, and cs_sininit expands them in place",
        "; at launch. Until it has, this is not a sine table.",
        "",
        "CS_SINPK  equ %d             ; where the codes begin in the table" % PK,
        "CS_SIND0  equ %d             ; the first difference, sin 1 - sin 0" % d0,
        "CS_SINFIX equ %d               ; the one step whose difference is -3, as CL" % fixcl,
        "",
        "    times CS_SINPK db 0",
    ]
    for i in range(0, NCODE, 16):
        out.append("    db " + ", ".join("0x%02X" % b for b in pk[i:i + 16]))
    out += [
        "%if $ - cs_sintab != " + str(SIZE),
        '  %error "cssin.inc: the table is not 257 words"',
        "%endif",
        "",
    ]
    return "\n".join(out)


def main(argv):
    text = render()
    if "--check" in argv:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != text:
            print("cssin: apps/skies/cssin.inc is not what tools/cssin.py "
                  "generates - run it and commit the result")
            return 1
        return 0
    open(OUT, "w").write(text)
    print("cssin: %s, %d bytes of codes behind %d zeros" % (OUT, NCODE, PK))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

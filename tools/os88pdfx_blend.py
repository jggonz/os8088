#!/usr/bin/env python3
"""os8088 - tools/os88pdfx_blend.py   PDF fixtures for AP-13 (PAGEDESK-SPEC 20.22.10)

    os88pdfx_blend.py write DIR        write every fixture (deterministic: byte-identical runs)
    os88pdfx_blend.py check DIR HARNESS BANK [--shots DIR]
                                       render each fixture with PDREND's host build (PDB_DUMP: the
                                       8-bit strips before quantising) and with `mutool draw -A 0 -c
                                       gray -r 72`, and report the differing-pixel rate per fixture

Every coordinate is an integer at 72 dpi, so no edge is partly covered and mutool's
reference is exact (anti-aliasing off); the fixtures use only grey and PDF 1.4
transparency, no fonts. Provenance: generated by this script, no third-party content."""
import os, subprocess, sys, struct, tempfile

W = H = 160

def pdf(objs, root=1):
    out = bytearray(b"%PDF-1.4\n"); offs = {}
    for n in sorted(objs):
        offs[n] = len(out)
        body = objs[n]
        if isinstance(body, tuple):                       # (dict-text, stream-bytes)
            d, s = body
            out += b"%d 0 obj\n<< %s /Length %d >>\nstream\n" % (n, d.encode(), len(s)) + s + b"\nendstream\nendobj\n"
        else:
            out += b"%d 0 obj\n%s\nendobj\n" % (n, body.encode())
    x = len(out); top = max(objs) + 1
    out += b"xref\n0 %d\n0000000000 65535 f \n" % top
    for n in range(1, top): out += b"%010d 00000 n \n" % offs[n]
    out += b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (top, root, x)
    return bytes(out)

def page(content, res, extra=None):
    objs = {1: "<< /Type /Catalog /Pages 2 0 R >>",
            2: "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            3: "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] /Contents 4 0 R /Resources << %s >> >>" % (W, H, res),
            4: ("", content.encode())}
    if extra: objs.update(extra)
    return pdf(objs)

def rect(x, y, w, h, g): return "%.3f g %d %d %d %d re f\n" % (g, x, y, w, h)

def fx_alpha():
    c = "".join(rect(i * 20, 0, 20, 160, i / 7.0) for i in range(8))
    c += "/A50 gs 0 g 10 10 70 70 re f\n/A25 gs 1 g 50 50 50 50 re f\n"
    c += "/A50 gs 0.3 G 8 w 30 100 80 40 re S\n"
    c += "/A80 gs 1 g 120 20 30 120 re f\n"
    gs = {5: "<< /ca 0.5 /CA 0.5 >>", 6: "<< /ca 0.25 /CA 0.25 >>", 7: "<< /ca 0.8 /CA 0.8 >>"}
    return page(c, "/ExtGState << /A50 5 0 R /A25 6 0 R /A80 7 0 R >>", gs)

BMS = ["Normal", "Multiply", "Screen", "Overlay", "Darken", "Lighten", "ColorDodge", "ColorBurn",
       "HardLight", "SoftLight", "Difference", "Exclusion", "Hue", "Saturation", "Color", "Luminosity"]
def fx_blend():
    c = ""; gs = {}; names = []
    for i, bm in enumerate(BMS):
        cx, cy = (i % 4) * 40, (i // 4) * 40
        c += rect(cx, cy, 20, 40, 0.25) + rect(cx + 20, cy, 20, 40, 0.75)
        c += rect(cx + 5, cy + 22, 30, 4, 0.0) + rect(cx + 5, cy + 14, 30, 4, 1.0)
        n = 5 + i; gs[n] = "<< /BM /%s /ca 0.8 >>" % bm; names.append("/B%d %d 0 R" % (i, n))
        c += "q /B%d gs 0.6 g %d %d 30 30 re f Q\n" % (i, cx + 5, cy + 5)
    return page(c, "/ExtGState << %s >>" % " ".join(names), gs)

def fx_group():
    form = ("/Type /XObject /Subtype /Form /BBox [0 0 160 160] /Group << /S /Transparency /I true >> /Resources << >>",
            (rect(0, 0, 1, 1, 0) + "0 g 10 10 40 40 re f 0.5 g 30 30 40 40 re f\n").encode())
    formk = ("/Type /XObject /Subtype /Form /BBox [0 0 160 160] /Group << /S /Transparency /I true /K true >> /Resources << /ExtGState << /H 5 0 R >> >>",
             b"/H gs 0 g 10 10 40 40 re f 0.5 g 30 30 40 40 re f\n")
    c = rect(0, 0, 160, 160, 0.9) + rect(0, 70, 160, 20, 0.4)
    c += "q /H gs 1 0 0 1 0 0 cm /G1 Do Q\n"                     # a group at ca .5
    c += "q 1 0 0 1 80 0 cm /H gs 0 g 10 10 40 40 re f 0.5 g 30 30 40 40 re f Q\n"   # the same, ungrouped
    c += "q 1 0 0 1 0 80 cm /H gs /G2 Do Q\n"                   # a knockout group at ca .5
    gs = {5: "<< /ca 0.5 /CA 0.5 >>", 6: form, 7: formk}
    return page(c, "/ExtGState << /H 5 0 R >> /XObject << /G1 6 0 R /G2 7 0 R >>", gs)

def fx_smask(kind):
    g = "/Type /XObject /Subtype /Form /BBox [0 0 160 160] /Group << /S /Transparency /CS /DeviceGray >> /Resources << /ExtGState << /H 6 0 R >> >>"
    if kind == "lum":
        mc = "".join(rect(20 + i * 30, 0, 30, 160, i / 3.0) for i in range(4))
        sm = "<< /Type /ExtGState /SMask << /Type /Mask /S /Luminosity /G 7 0 R /BC [0] >> >>"
    else:
        mc = "/H gs 1 g 20 20 60 120 re f 80 60 60 40 re f\n"
        sm = "<< /Type /ExtGState /SMask << /Type /Mask /S /Alpha /G 7 0 R >> >>"
    c = rect(0, 0, 160, 160, 1.0) + rect(0, 60, 160, 40, 0.5) + "q /M gs 0 g 0 0 160 160 re f Q\n"
    c += "/M2 gs 0 g 10 120 30 30 re f\n"                       # None again: opaque
    objs = {5: sm, 6: "<< /ca 0.5 >>", 7: (g, mc.encode()), 8: "<< /SMask /None >>"}
    return page(c, "/ExtGState << /M 5 0 R /M2 8 0 R >>", objs)

def fx_image():
    img = bytes([0, 64, 128, 255, 40, 90, 200, 255, 255, 200, 90, 40, 255, 128, 64, 0])
    sm = bytes([255, 255, 0, 0, 255, 128, 128, 0, 0, 128, 128, 255, 0, 0, 255, 255])
    mk = bytes([0xAA, 0x55] * 4)                                # 8x8 1-bit stencil: a set bit is masked out
    c = rect(0, 0, 160, 160, 0.8) + rect(0, 70, 160, 20, 0.2)
    c += "q 80 0 0 80 0 80 cm /I1 Do Q\nq 64 0 0 64 90 90 cm /I2 Do Q\n"
    objs = {5: ("/Type /XObject /Subtype /Image /Width 4 /Height 4 /ColorSpace /DeviceGray /BitsPerComponent 8 /SMask 6 0 R", img),
            6: ("/Type /XObject /Subtype /Image /Width 4 /Height 4 /ColorSpace /DeviceGray /BitsPerComponent 8", sm),
            7: ("/Type /XObject /Subtype /Image /Width 4 /Height 4 /ColorSpace /DeviceGray /BitsPerComponent 8 /Mask 8 0 R", img),
            8: ("/Type /XObject /Subtype /Image /Width 8 /Height 8 /ImageMask true /BitsPerComponent 1", mk)}
    return page(c, "/XObject << /I1 5 0 R /I2 7 0 R >>", objs)

FIXTURES = {"alpha": fx_alpha, "blend": fx_blend, "group": fx_group,
            "smask_lum": lambda: fx_smask("lum"), "smask_alpha": lambda: fx_smask("alpha"), "image": fx_image}

def write(d):
    os.makedirs(d, exist_ok=True)
    for n, f in FIXTURES.items():
        open(os.path.join(d, n + ".pdf"), "wb").write(f())

def read_pgm(p):
    b = open(p, "rb").read(); parts = b.split(None, 4)
    w, h = int(parts[1]), int(parts[2]); return w, h, parts[4][-(w * h):]

def refs(src, tmp, n):
    """the two independent readers: MuPDF and Poppler, grey, 72 dpi, anti-aliasing off"""
    import numpy as np
    m = os.path.join(tmp, n + ".m.pgm")
    subprocess.run(["mutool", "draw", "-A", "0", "-c", "gray", "-r", "72", "-o", m, src, "1"], check=True, capture_output=True)
    subprocess.run(["pdftoppm", "-r", "72", "-gray", "-aa", "no", "-aaVector", "no", "-singlefile", src, os.path.join(tmp, n + ".p")], check=True)
    out = []
    for f in (m, os.path.join(tmp, n + ".p.pgm")):
        w, h, b = read_pgm(f); out.append(np.frombuffer(b, dtype=np.uint8).reshape(h, w).astype(int))
    return out

def check(d, harness, bank, shots=None):
    import numpy as np
    tmp = tempfile.mkdtemp()
    print("%-12s %5s  %-22s %-22s" % ("fixture", "rows", "vs MuPDF  mean >8 >24", "vs Poppler mean >8 >24"))
    for n in FIXTURES:
        src = os.path.join(d, n + ".pdf")
        dump = os.path.join(tmp, n + ".dump")
        subprocess.run([harness, "render", src, "0", "100", "0", "4", "1/1", str(W), str(H), "0", "0",
                        os.path.join(tmp, n + ".ppm"), bank], check=True, capture_output=True, env=dict(os.environ, PDB_DUMP=dump))
        mu, po = refs(src, tmp, n)
        raw = np.fromfile(dump, dtype=np.uint8)
        o = raw[:W * H].reshape(H, W).astype(int)
        drawn = raw[W * H:W * H + H].astype(bool)
        cols = []
        for r in (mu, po):
            df = np.abs(o[drawn] - r[drawn]); cols.append("%5.2f %5.1f%% %5.1f%%" % (df.mean(), (df > 8).mean() * 100, (df > 24).mean() * 100))
        print("%-12s %5d  %-22s %-22s" % (n, int(drawn.sum()), cols[0], cols[1]))
        if shots:
            from PIL import Image
            os.makedirs(shots, exist_ok=True)
            df = np.abs(o[drawn] - po[drawn])
            side = np.concatenate([o[drawn], np.full((df.shape[0], 4), 128), po[drawn], np.full((df.shape[0], 4), 128), mu[drawn],
                                   np.full((df.shape[0], 4), 128), 255 - np.clip(df * 4, 0, 255)], axis=1)
            Image.fromarray(side.astype("uint8")).save(os.path.join(shots, n + ".png"))
    return 0

if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "write": write(sys.argv[2])
    elif len(sys.argv) >= 5 and sys.argv[1] == "check":
        shots = sys.argv[sys.argv.index("--shots") + 1] if "--shots" in sys.argv else None
        sys.exit(check(sys.argv[2], sys.argv[3], sys.argv[4], shots))
    else: print(__doc__); sys.exit(2)

#!/usr/bin/env python3
"""Write gbflags.asm, RealDMG's dead-flag gate ROM, for tools/gbours.py.

The recompiler drops the flags of INC r, DEC r and ADD HL,rr when the
instructions after it in the block overwrite them before anything reads them
(docs/REALDMG-SPEC.md section 16.1.2). Blargg's cpu_instrs cannot see that: it
runs the instruction under test from RAM, which is never translated. This ROM
runs its sequences from ROM, each in a loop long enough that it is
translated (a PC is on its 64th entry) and then runs translated, and folds
AF, BC, DE and HL after every pass into a sum it prints on the link port -
"Sum xxxx", then "Passed". tests/gbcpu.py runs it with the recompiler and
without, and the two sums must agree.

The sequences are seeded pseudo-random runs of register-only instructions,
weighted towards the three the pass can drop and the ones it looks past:
loads, 16-bit INC/DEC, a store to HRAM or WRAM, a PUSH/POP AF pair, a JR cc
to the next instruction, and every flag writer and reader in between.
"""
import random
import sys

R = ["b", "c", "d", "e", "h", "l", "a"]
SEQS = 160
PASSES = 100            # each sequence's loop: past RDG_JITHOT's 64, translated


def candidate(rnd):
    k = rnd.random()
    if k < 0.6:
        return "%s %s" % (rnd.choice(["inc", "dec"]), rnd.choice(R))
    return "add hl, %s" % rnd.choice(["bc", "de", "hl", "sp"])


def neutral(rnd, tag):
    k = rnd.randrange(10)
    if k < 4:
        return ["ld %s, %s" % (rnd.choice(R), rnd.choice(R))]
    if k < 6:
        return ["ld %s, $%02X" % (rnd.choice(R), rnd.randrange(256))]
    if k == 6:
        return ["%s %s" % (rnd.choice(["inc", "dec"]), rnd.choice(["bc", "de"]))]
    if k == 7:
        return [rnd.choice(["ldh [$FF90], a", "ld [$C100], a", "ld a, [$C101]",
                            "ldh a, [$FF91]"])]
    if k == 8:
        return ["push bc", "pop de"]
    return ["nop"]


def writer(rnd, tag):
    k = rnd.randrange(16)
    if k < 6:
        op = rnd.choice(["add", "adc", "sub", "sbc", "and", "xor", "or", "cp"])
        src = rnd.choice(R + ["$%02X" % rnd.randrange(256)])
        return ["%s a, %s" % (op, src)]
    if k < 8:
        return [candidate(rnd)]
    if k == 8:
        return [rnd.choice(["rlca", "rrca", "rla", "rra", "cpl", "scf", "ccf", "daa"])]
    if k == 9:
        op = rnd.choice(["rlc", "rrc", "rl", "rr", "sla", "sra", "swap", "srl"])
        return ["%s %s" % (op, rnd.choice(R))]
    if k == 10:
        return ["bit %d, %s" % (rnd.randrange(8), rnd.choice(R))]
    if k == 11:
        return ["push bc", "pop af"]
    if k == 12:
        return ["push af", "pop bc"]
    if k == 13:
        return ["jr %s, %s" % (rnd.choice(["z", "nz", "c", "nc"]), tag), tag + ":"]
    if k == 14:
        return ["%s %d, %s" % (rnd.choice(["set", "res"]), rnd.randrange(8), rnd.choice(R))]
    return ["ld a, [$C101]"]


def sequence(rnd, s):
    out, n = [], 0
    for _ in range(rnd.randrange(3, 9)):
        out.append(candidate(rnd))
        for _ in range(rnd.randrange(0, 4)):
            n += 1
            out += neutral(rnd, ".n%d" % n)
        n += 1
        out += writer(rnd, ".w%d" % n)
    return out


def main(path):
    rnd = random.Random(8088)
    L = ["; GENERATED by tools/gbprof/gbflags.py - see there", "",
         'SECTION "header", ROM0[$100]', "    nop", "    jp Start", "    ds $150 - @, 0", "",
         'SECTION "main", ROM0[$150]', "Start:", "    di", "    ld sp, $DFF0",
         "    xor a", "    ldh [$FF80], a", "    ldh [$FF81], a", "    ldh [$FF90], a",
         "    ldh [$FF91], a", "    ld [$C100], a", "    ld [$C101], a"]
    for s in range(SEQS):
        L += ["    call Seq%d" % s]
    L += ["    ld hl, SumText", "    call PutStr", "    ldh a, [$FF81]", "    call PutHex",
          "    ldh a, [$FF80]", "    call PutHex", "    ld hl, Newline", "    call PutStr",
          "    ld hl, Passed", "    call PutStr", ".done:", "    jr .done", "",
          "PutStr:", "    ld a, [hl+]", "    or a", "    ret z", "    call SerOut", "    jr PutStr",
          "SerOut:", "    ldh [$FF01], a", "    ld a, $81", "    ldh [$FF02], a", "    ret",
          "PutHex:", "    push af", "    swap a", "    call .n", "    pop af",
          ".n:", "    and $0F", "    add a, $30", "    cp $3A", "    jr c, .o",
          "    add a, 7", ".o:", "    jp SerOut", "",
          "; the four pairs pushed before the call, into the sum at FF80",
          "Fold:", "    ld hl, sp+2", "    ld b, 8", ".l:", "    ldh a, [$FF80]", "    rlca",
          "    xor [hl]", "    ldh [$FF80], a", "    ldh a, [$FF81]", "    add a, [hl]",
          "    rrca", "    ldh [$FF81], a", "    inc hl", "    dec b", "    jr nz, .l",
          "    ret", ""]
    for s in range(SEQS):
        k = [rnd.randrange(256) for _ in range(8)]
        if s % 2 == 0:              # (half in ROM0, half in 4000-7FFF)
            L += ['SECTION "seq%d", ROM0' % s]
        else:
            L += ['SECTION "seq%d", ROMX' % s]
        L += ["Seq%d:" % s, "    ld a, %d" % PASSES, "    ld [$C0F0], a", ".p:",
              "    ld a, [$C0F0]", "    ld b, a", "    add a, $%02X" % k[0], "    ld c, a",
              "    push bc", "    pop af", "    xor $%02X" % k[1], "    ld b, a",
              "    add a, $%02X" % k[2], "    ld c, a", "    add a, $%02X" % k[3], "    ld d, a",
              "    add a, $%02X" % k[4], "    ld e, a", "    add a, $%02X" % k[5], "    ld h, a",
              "    add a, $%02X" % k[6], "    ld l, a", "    xor $%02X" % k[7]]
        L += ["    " + x if not x.endswith(":") else x for x in sequence(rnd, s)]
        L += ["    push af", "    push bc", "    push de", "    push hl", "    call Fold",
              "    add sp, 8", "    ld a, [$C0F0]", "    dec a", "    ld [$C0F0], a",
              "    jp nz, .p", "    ret", ""]
    L += ['SECTION "text", ROM0', 'SumText:', '    db "Sum ", 0', 'Newline:', '    db 10, 0',
          'Passed:', '    db "Passed", 10, 0']
    open(path, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])

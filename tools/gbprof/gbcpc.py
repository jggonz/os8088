#!/usr/bin/env python3
"""Write gbcpc.asm, RealDMG's gate for the copies through (C) the recompiler
takes in one step (cpc_ff, docs/REALDMG-SPEC.md section 16.6), for
tools/gbours.py.

    LD A,(HL+) / LD (C),A / INC C / DEC B / JR NZ,-6     (RAM to HRAM)
    LD A,(C) / INC C / LD (HL+),A / DEC B / JR NZ,-6     (HRAM to RAM)

are Looney Tunes' objects, 32 bytes out to HRAM and back eight times a
frame, and every cartridge's boot copy of its DMA routine. This ROM runs
seeded copies of both shapes from ROM - half in ROM0, half in 4000-7FFF -
with a timer interrupt landing every ~448 M-cycles, so that some fit before
the event and are taken whole and some do not and are declined. The ranges
are the shortcut's and its edges': C from 84h (FF80-FF83 hold the sums), and past FFh into the I/O
page (declined); HL in WRAM, in VRAM, in HRAM itself, and
in ROM (declined). Each copy's exit folds AF, BC and HL and the bytes it
wrote into one sum, the handler the F it interrupted into another; both are
printed on the link port, "Sum xxxxyyyy", then "Passed". tests/gbcpu.py
runs it with the recompiler and without and the sums must agree; its
control (RT_CPCBUG) takes the shortcut the wrong way round and must see
them differ.
"""
import random
import sys

SEQS = 96
PASSES = 24             # each copy run this many times: its block past
                        #   RDG_JITHOT's 64 once r is 3 or more


def main(path):
    rnd = random.Random(8088)
    L = ["; GENERATED by tools/gbprof/gbcpc.py - see there", "",
         'SECTION "timer", ROM0[$50]', "    jp Timer", "",
         'SECTION "header", ROM0[$100]', "    nop", "    jp Start", "    ds $150 - @, 0", "",
         'SECTION "main", ROM0[$150]', "Start:", "    di", "    ld sp, $DFF0",
         ".vb:", "    ldh a, [$FF44]", "    cp 144", "    jr c, .vb",
         "    xor a", "    ldh [$FF40], a",                  # the LCD off to seed VRAM,
         "    ldh [$FF80], a", "    ldh [$FF81], a", "    ldh [$FF82], a",
         "    ldh [$FF83], a",
         "    ld hl, $C000", "    ld bc, $2000",           # WRAM, VRAM, HRAM seeded
         ".w:", "    ld a, l", "    xor h", "    ld [hl+], a", "    dec bc", "    ld a, b",
         "    or c", "    jr nz, .w",
         "    ld hl, $8000", "    ld bc, $0400",
         ".v:", "    ld a, l", "    add a, h", "    ld [hl+], a", "    dec bc", "    ld a, b",
         "    or c", "    jr nz, .v",
         "    ld a, $91", "    ldh [$FF40], a",              # and on again: a frame
         "    ld c, $84", ".hr:", "    ld a, c", "    cpl", "    ld [$FF00+c], a", "    inc c",
         "    ld a, c", "    cp $FF", "    jr nz, .hr",
         "    ld a, $90", "    ldh [$FF06], a",               # TMA: 112 ticks
         "    ld a, $05", "    ldh [$FF07], a",               # TAC: on, 4 M a tick
         "    ld a, $04", "    ldh [$FFFF], a",               # IE: the timer
         "    xor a", "    ldh [$FF0F], a", "    ei"]
    for s in range(SEQS):
        L += ["    call Seq%d" % s]
    L += ["    di",
          "    ld hl, SumText", "    call PutStr", "    ldh a, [$FF81]", "    call PutHex",
          "    ldh a, [$FF80]", "    call PutHex", "    ldh a, [$FF83]", "    call PutHex",
          "    ldh a, [$FF82]", "    call PutHex", "    ld hl, Newline", "    call PutStr",
          "    ld hl, Passed", "    call PutStr", ".done:", "    jr .done", "",
          "PutStr:", "    ld a, [hl+]", "    or a", "    ret z", "    call SerOut", "    jr PutStr",
          "SerOut:", "    ldh [$FF01], a", "    ld a, $81", "    ldh [$FF02], a", "    ret",
          "PutHex:", "    push af", "    swap a", "    call .n", "    pop af",
          ".n:", "    and $0F", "    add a, $30", "    cp $3A", "    jr c, .o",
          "    add a, 7", ".o:", "    jp SerOut", "",
          "; the timer: the F it interrupted, into the sum at FF82",
          "Timer:", "    push af", "    push bc", "    push af", "    pop bc",
          "    ldh a, [$FF82]", "    rlca", "    xor c", "    ldh [$FF82], a",
          "    ldh a, [$FF83]", "    add a, c", "    rrca", "    ldh [$FF83], a",
          "    pop bc", "    pop af", "    reti", "",
          "; the three pairs pushed before the call, then the B bytes from HL,",
          "; into the sum at FF80",
          "Fold:", "    ld hl, sp+2", "    ld b, 6", "    call .f",
          "    ld a, [$C0F2]", "    ld l, a", "    ld a, [$C0F3]", "    ld h, a",
          "    ld a, [$C0F4]", "    ld b, a",
          ".f:", "    ldh a, [$FF80]", "    rlca",
          "    xor [hl]", "    ldh [$FF80], a", "    ldh a, [$FF81]", "    add a, [hl]",
          "    rrca", "    ldh [$FF81], a", "    inc hl", "    dec b", "    jr nz, .f",
          "    ret", ""]
    for s in range(SEQS):
        out = s % 3 != 2                    # RAM to HRAM, or HRAM to RAM
        r = rnd.choice([1, 2, 3, 5, 8, 12, 16, 24, 32, 32, 40, 48])
        c = rnd.randrange(0x84, 0xFF - r + 1)    # (FF80-FF83: the sums)
        k = rnd.randrange(12)
        if k == 0:                          # C past FFh, into the I/O page:
            c = rnd.randrange(0x100 - r + 1, 0x100)  #   declined (reads only)
            out = False
        if k == 1 and out:                  # C below 80h: the I/O page itself
            c = rnd.randrange(0x40, 0x7F - r)        #   (reads only), declined
            out = False
        if k in (2, 3):
            hl = 0x8000 + rnd.randrange(0x400 - r)   # VRAM, the LCD off
        elif k == 4:
            hl = 0xFF84 + rnd.randrange(0x7B - r) if r < 0x70 else 0xC100
        elif k == 5 and out:
            hl = 0x0150 + rnd.randrange(0x100)       # ROM: declined
        else:
            hl = 0xC100 + rnd.randrange(0x1E00 - r)  # WRAM
        if not out and hl < 0x8000:
            hl = 0xC100
        # what Fold checksums: the bytes written
        dst, n = (0xFF00 + c, r) if out else (hl, r)
        if dst + n > 0x10000 or (dst < 0xFF80 <= dst + n):
            dst, n = 0xC100, 8
        L += ['SECTION "seq%d", %s' % (s, "ROM0" if s % 2 == 0 else "ROMX")]
        L += ["Seq%d:" % s, "    ld a, %d" % PASSES, "    ld [$C0F0], a",
              "    ld a, $%02X" % (dst & 0xFF), "    ld [$C0F2], a",
              "    ld a, $%02X" % (dst >> 8), "    ld [$C0F3], a",
              "    ld a, %d" % n, "    ld [$C0F4], a", ".p:",
              "    ld a, $%02X" % rnd.randrange(256),               # F seeded,
              "    add a, $%02X" % rnd.randrange(256),              #   carry too
              "    ld hl, $%04X" % hl, "    ld bc, $%02X%02X" % (r, c), "    jr .l", ".l:"]
        if out:
            L += ["    ld a, [hl+]", "    ld [$FF00+c], a", "    inc c"]
        else:
            L += ["    ld a, [$FF00+c]", "    inc c", "    ld [hl+], a"]
        L += ["    dec b", "    jr nz, .l"]
        L += ["    push af", "    push bc", "    push hl", "    call Fold",
              "    add sp, 6", "    ld a, [$C0F0]", "    dec a", "    ld [$C0F0], a",
              "    jp nz, .p", "    ret", ""]
    L += ['SECTION "text", ROM0', 'SumText:', '    db "Sum ", 0', 'Newline:', '    db 10, 0',
          'Passed:', '    db "Passed", 10, 0']
    open(path, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])

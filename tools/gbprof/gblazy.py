#!/usr/bin/env python3
"""Write gblazy.asm, RealDMG's gate for the countdown loops whose DEC r the
recompiler leaves without F (docs/REALDMG-SPEC.md section 16.1.3), for
tools/gbours.py.

A JR NZ back to its own block's start after DEC r is translated as a bare
`dec r` and a branch on its ZF, and F is made only where somebody can see
it: the fall-through out of the loop, and the event an interrupt is taken
at. This ROM runs seeded loops of that shape from ROM - half in ROM0, half
in 4000-7FFF, each long enough to be translated - with a timer interrupt
landing every ~128 M-cycles, which is to say at the loop's JR again and
again. The handler folds the F it pushes into one sum and every loop's exit
folds AF, BC, DE and HL into another; both are printed on the link port,
"Sum xxxxyyyy", then "Passed". tests/gbcpu.py runs it with the recompiler
and without, and the sums must agree; its control (RT_LAZYBUG) takes the
event with F stale and must see them differ.

The bodies are what the translator's rule is about: register writers and
readers, the counter left alone, stores to HRAM and WRAM, and a write to IF
that takes the interrupt INSIDE the body - which is where F must be exact
whether the loop was made lazy or not. No NOP and no HALT: the interpreter
checks for an event at a NOP and translated code does not (section 20.6),
and the sums would part for that alone.
"""
import random
import sys

R = ["b", "c", "d", "e", "h", "l", "a"]
SEQS = 120
PASSES = 3              # each loop run this many times...
COUNT = 150             # ...of this many passes: past RDG_JITHOT's 64


def body_op(rnd, ctr, tag):
    """one body instruction (or a short run) that leaves the counter alone"""
    rs = [r for r in R if r != ctr]
    k = rnd.randrange(20)
    if k < 3:
        op = rnd.choice(["add", "adc", "sub", "sbc", "and", "xor", "or", "cp"])
        if ctr == "a":
            return ["%s a, %s" % ("cp", rnd.choice(rs))]
        return ["%s a, %s" % (op, rnd.choice(rs + ["$%02X" % rnd.randrange(256)]))]
    if k < 6:
        return ["%s %s" % (rnd.choice(["inc", "dec"]), rnd.choice(rs))]
    if k == 6:
        return ["add hl, %s" % rnd.choice(["bc", "de", "hl", "sp"])] if ctr not in "hl" \
            else ["inc de"]
    if k == 7:
        return ["ld %s, %s" % (rnd.choice(rs), rnd.choice(rs))]
    if k == 8:
        return ["ld %s, $%02X" % (rnd.choice(rs), rnd.randrange(256))]
    if k == 9:
        return [rnd.choice(["ldh [$FF90], a", "ld [$C100], a", "ldh a, [$FF91]",
                            "ld a, [$C101]"])] if ctr != "a" else ["ldh [$FF90], a"]
    if k == 10:
        if ctr == "a":
            return ["ld c, d"] if ctr != "c" else ["ld d, e"]
        return ["ld a, $04", "ldh [$FF0F], a"]          # the timer's, now
    if k == 11:
        op = rnd.choice(["rlc", "rrc", "rl", "rr", "sla", "sra", "swap", "srl"])
        return ["%s %s" % (op, rnd.choice(rs))]
    if k == 12:
        return ["bit %d, %s" % (rnd.randrange(8), rnd.choice(rs))]
    if k == 13:
        if ctr == "a":
            return ["scf"]
        return [rnd.choice(["rlca", "rrca", "rla", "rra", "cpl", "scf", "ccf", "daa"])]
    if k == 14:
        return ["push de", "pop de"]
    if k == 15 and ctr != "a":
        return ["push af", "pop af"]
    if k == 16:
        return ["%s %s" % (rnd.choice(["inc", "dec"]), rnd.choice(["bc", "de"]))] \
            if ctr not in "bc" else ["inc de"]
    return ["ld %s, %s" % (rnd.choice(rs), rnd.choice(rs))]


def loop(rnd, s):
    ctr = rnd.choice(["b", "c", "h", "l", "b", "c", "a"])
    body = []
    for _ in range(rnd.randrange(0, 8)):
        body += body_op(rnd, ctr, ".x%d" % s)
    return ctr, body


def main(path):
    rnd = random.Random(8086)
    L = ["; GENERATED by tools/gbprof/gblazy.py - see there", "",
         'SECTION "timer", ROM0[$50]', "    jp Timer", "",
         'SECTION "header", ROM0[$100]', "    nop", "    jp Start", "    ds $150 - @, 0", "",
         'SECTION "main", ROM0[$150]', "Start:", "    di", "    ld sp, $DFF0",
         "    xor a", "    ldh [$FF80], a", "    ldh [$FF81], a", "    ldh [$FF82], a",
         "    ldh [$FF83], a", "    ldh [$FF90], a", "    ldh [$FF91], a",
         "    ld [$C100], a", "    ld [$C101], a",
         "    ld a, $E0", "    ldh [$FF06], a",               # TMA: 32 ticks
         "    ld a, $05", "    ldh [$FF07], a",               # TAC: on, 4 M a tick
         "    ld a, $04", "    ldh [$FFFF], a",               # IE: the timer
         "    xor a", "    ldh [$FF0F], a", "    ei"]
    for s in range(SEQS):
        L += ["    call Seq%d" % s]
    L += ["    di",
          "    ld hl, SumText", "    call PutStr", "    ldh a, [$FF81]", "    call PutHex",
          "    ldh a, [$FF80]", "    call PutHex", "    ldh a, [$FF83]", "    call PutHex",
          "    ldh a, [$FF82]", "    call PutHex", "    ld hl, Newline", "    call PutStr",
          "    ld hl, Passed", "    call PutStr", ".done:", "    jr .done", "",
          "PutStr:", "    ld a, [hl+]", "    or a", "    ret z", "    call SerOut", "    jr PutStr",
          "SerOut:", "    ldh [$FF01], a", "    ld a, $81", "    ldh [$FF02], a", "    ret",
          "PutHex:", "    push af", "    swap a", "    call .n", "    pop af",
          ".n:", "    and $0F", "    add a, $30", "    cp $3A", "    jr c, .o",
          "    add a, 7", ".o:", "    jp SerOut", "",
          "; the timer: the F it interrupted, into the sum at FF82",
          "Timer:", "    push af", "    push bc", "    push af", "    pop bc",
          "    ldh a, [$FF82]", "    rlca", "    xor c", "    ldh [$FF82], a",
          "    ldh a, [$FF83]", "    add a, c", "    rrca", "    ldh [$FF83], a",
          "    pop bc", "    pop af", "    reti", "",
          "; the four pairs pushed before the call, into the sum at FF80",
          "Fold:", "    ld hl, sp+2", "    ld b, 8", ".l:", "    ldh a, [$FF80]", "    rlca",
          "    xor [hl]", "    ldh [$FF80], a", "    ldh a, [$FF81]", "    add a, [hl]",
          "    rrca", "    ldh [$FF81], a", "    inc hl", "    dec b", "    jr nz, .l",
          "    ret", ""]
    for s in range(SEQS):
        k = [rnd.randrange(256) for _ in range(8)]
        ctr, body = loop(rnd, s)
        L += ['SECTION "seq%d", %s' % (s, "ROM0" if s % 2 == 0 else "ROMX")]
        L += ["Seq%d:" % s, "    ld a, %d" % PASSES, "    ld [$C0F0], a", ".p:",
              "    ld a, $%02X" % k[0], "    ld b, a", "    add a, $%02X" % k[1], "    ld c, a",
              "    push bc", "    pop af", "    xor $%02X" % k[2], "    ld d, a",
              "    add a, $%02X" % k[3], "    ld e, a", "    add a, $%02X" % k[4], "    ld h, a",
              "    add a, $%02X" % k[5], "    ld l, a", "    xor $%02X" % k[6],
              "    ld %s, %d" % (ctr, COUNT), "    jr .l", ".l:"]
        L += ["    " + x for x in body]
        L += ["    dec %s" % ctr, "    jr nz, .l"]
        L += ["    push af", "    push bc", "    push de", "    push hl", "    call Fold",
              "    add sp, 8", "    ld a, [$C0F0]", "    dec a", "    ld [$C0F0], a",
              "    jp nz, .p", "    ret", ""]
    L += ['SECTION "text", ROM0', 'SumText:', '    db "Sum ", 0', 'Newline:', '    db 10, 0',
          'Passed:', '    db "Passed", 10, 0']
    open(path, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])

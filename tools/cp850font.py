#!/usr/bin/env python3
"""Generate the optional native CP850 glyphs from repository-authored art.

ASCII is copied from the running face by KEYBOARD.DRV. This table contains
128..255 only and belongs to that module, never the resident kernel.
CP437 shapes are shared by Unicode character identity, not byte position.
The remaining accented capitals reuse its base/accent construction; the
few CP850-only symbols are authored here. No external font is an input.
"""

from pathlib import Path
import sys
import unicodedata

import cp437font as cp

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "kernel" / "keyfont-data.inc"
BASE = dict(cp.BASE)
BASE.update({
    "I": ["#####", "..#..", "..#..", "..#..", "#####"],
    "Y": ["#...#", ".#.#.", "..#..", "..#..", "..#.."],
})
ACCENTS = {"\u0300": "grave", "\u0301": "acute", "\u0302": "circ",
           "\u0303": "tilde", "\u0308": "trema", "\u030a": "ring",
           "\u0327": "cedil"}

# The 8x8 convention is cp437font.py's: row zero first, bit 7 leftmost.
EXTRA = {
    "ø": cp.art("........", "........", "..###.#.", ".#..##..",
                ".#.#.#..", ".##..#..", "#.###..."),
    "Ø": cp.art("..####.#", ".#....#.", ".#...##.", ".#..#.#.",
                ".#.#..#.", ".##...#.", ".#.####."),
    "×": cp.art("........", "........", ".#...#..", "..#.#...",
                "...#....", "..#.#...", ".#...#.."),
    "®": cp.art("..####..", ".#....#.", "#.###..#", "#.#..#.#",
                "#.###..#", "#.#..#.#", ".#....#.", "..####.."),
    "©": cp.art("..####..", ".#....#.", "#..###.#", "#.#....#",
                "#.#....#", "#..###.#", ".#....#.", "..####.."),
    "¤": cp.art("........", ".#...#..", "..###...", ".#...#..",
                ".#...#..", "..###...", ".#...#.."),
    "ð": cp.art("..##.#..", "...##...", "..#.##..", ".....#..",
                "..####..", ".#...#..", "..###..."),
    "Ð": cp.art(".####...", ".#...#..", ".#....#.", "####..#.",
                ".#....#.", ".#...#..", ".####..."),
    "ı": cp.art("........", "........", "..##....", "...#....",
                "...#....", "...#....", "..###..."),
    "¦": cp.art("...##...", "...##...", "...##...", "........",
                "...##...", "...##...", "...##..."),
    "þ": cp.art(".##.....", "..#.....", "..####..", "..#...#.",
                "..#...#.", "..####..", "..#.....", ".###...."),
    "Þ": cp.art(".###....", "..#.....", "..####..", "..#...#.",
                "..#...#.", "..####..", "..#.....", ".###...."),
    "¯": cp.art(".#####.."),
    "´": cp.art("....#...", "...#...."),
    "\u00ad": cp.art("........", "........", "........", ".#####.."),
    "‗": cp.art("........", "........", "........", "........",
                "........", "........", ".#####..", ".#####.."),
    "¾": cp.art("##......", "..#...#.", ".#...#..", "..#.#.#.",
                "##.#..#.", "..#.####", ".#....#."),
    "¶": cp.CTRL[0x14],
    "§": cp.CTRL[0x15],
    "¸": cp.art("........", "........", "........", "........",
                "........", "...#....", "....#...", "..##...."),
    "¨": cp.art("..#.#..."),
    "¹": cp.art("..#.....", ".##.....", "..#.....", ".###...."),
    "³": cp.art(".##.....", "...#....", "..#.....", "...#....", ".##....."),
}


def glyph(code):
    ch = bytes([code]).decode("cp850")
    if ch in EXTRA:
        return EXTRA[ch]
    try:
        other = ch.encode("cp437")[0]
    except UnicodeEncodeError:
        other = None
    if other is not None:
        return cp.glyph(other)
    decomp = unicodedata.normalize("NFD", ch)
    if len(decomp) == 2 and decomp[0] in BASE and decomp[1] in ACCENTS:
        pat, top = cp.ACCENT[ACCENTS[decomp[1]]]
        return cp.over(cp.place(BASE[decomp[0]], 2), cp.place(pat, top))
    raise ValueError(f"no authored CP850 glyph for {code:02X} {ch!r}")


def build():
    lines = ["; Generated by tools/cp850font.py; do not edit.",
             "; CP850 128..255, eight rows per glyph; optional KEYBOARD.DRV data.",
             "klf_cp850:"]
    for code in range(128, 256):
        ch = bytes([code]).decode("cp850")
        rows = glyph(code)
        assert len(rows) == 8 and all(0 <= x <= 255 for x in rows)
        lines.append("    db " + ",".join(f"0x{x:02X}" for x in rows)
                     + f" ; {code:02X} {unicodedata.name(ch, 'UNNAMED')}")
    lines += ["klf_cp850_end:",
              "%if klf_cp850_end - klf_cp850 != 128 * 8",
              '  %error "optional CP850 font must contain 128 glyphs"',
              "%endif", ""]
    return "\n".join(lines)


def main():
    result = build()
    # Pin the requested examples independently of table order.
    for ch in "ñÑáéíóúü¿¡èàçùêë":
        assert any(glyph(ch.encode("cp850")[0])), ch
    assert glyph(0xFF) == [0] * 8       # non-breaking space
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != result:
            print("cp850font: kernel/keyfont-data.inc is stale")
            return 1
    elif "--show" in sys.argv:
        for code in range(128, 256):
            print(f"{code:02X} {bytes([code]).decode('cp850')}")
            print("\n".join(cp.show(glyph(code))))
    elif "--selfcheck" not in sys.argv:
        OUT.write_text(result)
    print("cp850font: 128 authored glyphs, 1024 optional bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())

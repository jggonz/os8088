#!/usr/bin/env python3
"""Compile the reference PLAY strings into nonblocking speaker note tables.

QBasic octave 0 starts at C=65.406 Hz (PLAY's octave numbering differs from
scientific pitch notation). Durations round to the OS's 18.2 Hz tone ticks;
32nd/64th notes have a one-tick minimum. No runtime BASIC parser is needed.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def compile_mml(text, tempo=160):
    octave, length = 4, 4
    result = []
    tokens = re.findall(r'M[BFNLS]|[TOLN]\d+|[A-G][+#-]?\d*', text.upper())
    for token in tokens:
        op = token[0]
        if op == 'M':
            continue
        if op == 'T':
            tempo = int(token[1:])
        elif op == 'O':
            octave = int(token[1:])
        elif op == 'L':
            length = int(token[1:])
        else:
            if op == 'N':
                assert token == 'N0'
                freq, duration = 0, length
            else:
                note = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}[op]
                tail = token[1:]
                if tail[:1] in ('+', '#', '-'):
                    note += -1 if tail[0] == '-' else 1
                    tail = tail[1:]
                duration = int(tail) if tail else length
                freq = round(440 * 2 ** ((note + (octave - 2)*12 - 9)/12))
            ticks = max(1, round(240 / tempo / duration * 18.2065))
            result.append((freq, ticks))
    return result


def songs():
    """Every score as (MML, [(Hz, ticks)]), in the order grmusic.inc lists
    them. This is the reference the gates decode the package's bytes against."""
    source = (ROOT / 'reference/gorillas/gorilla.bas').read_text()
    def plays(sub):
        body = source.split('\nSUB ' + sub + '\n', 1)[1].split('END SUB', 1)[0]
        return re.findall(r'PLAY "([^"]+)"', body)
    dance = plays('GorillaIntro (Player1$, Player2$)')
    mml = {
        'intro': plays('Intro')[0],
        'dance': ''.join(dance[:4]) + ''.join(dance[4:])*4,
        'throw': re.search(r'PLAY "(MBo0[^\"]+)"', source)[1],
        'impact': plays('DoExplosion (x#, y#)')[0],
        'hit': 'MBO0L16EFGEFDC',
        'victory': plays('VictoryDance (Player)')[0],
    }
    out = {}
    for name, text in mml.items():
        notes = compile_mml(text)
        if name == 'victory':
            notes.append((0, 4))        # Rest .2, rounded to BIOS ticks
        out[name] = (text, notes)
    return out


def frequencies():
    """gr_musichz: the rest, then every pitch the scores use, ascending."""
    return sorted({hz for _, notes in songs().values() for hz, _ in notes} | {0})


def generate():
    table = frequencies()
    # One byte a note: the gr_musichz index in bits 7..3, ticks in 2..0 (so the
    # pitch word is a mask away). A zero byte ends a sequence: every note lasts a tick.
    assert len(table) <= 32
    out = ['; Generated by tools/gorillas_music.py from reference/gorillas/gorilla.bas.',
           '; A byte a note: the gr_musichz index in bits 7..3, BIOS ticks in 2..0;',
           '; a zero byte ends a sequence.',
           'align 2', 'gr_musichz:',
           '    dw ' + ','.join(map(str, table))]
    for name, (text, notes) in songs().items():
        assert all(1 <= ticks <= 7 for _, ticks in notes)
        out += ['gr_music' + name + ':', '    ; PLAY "' + text + '"']
        body = [table.index(hz) << 3 | ticks for hz, ticks in notes] + [0]
        out += ['    db ' + ','.join(map(str, body[i:i+16])) for i in range(0, len(body), 16)]
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    path = ROOT / 'apps/gorillas/grmusic.inc'
    generated = generate()
    if args.check:
        assert path.read_text() == generated, 'grmusic.inc is stale'
        print('gorillas_music: reference PLAY scores match')
    else:
        path.write_text(generated)


if __name__ == '__main__':
    main()

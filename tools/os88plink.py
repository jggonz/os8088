#!/usr/bin/env python3
"""os88plink: the names a LINKED part takes from its package (SPEC.md 98.3.24.1).

    python3 tools/os88plink.py PKG.bin PKG.map PART.asm [-D NAME] -o LINK.inc

tools/pxlink.py's idea, for a package whose variables are not all bss: the
Video Player's kern_mega arm keeps its state in initialised words inside the
image, between its code, so "every symbol past the image's end" would leave
out the very words its cold part reads (apps/video/vcold.asm). So the PART
says what it takes, in its own source, one or more lines each:

    ;@data vp_rwhy vp_rasked VP_PRH ...   variables, tables and constants:
                                          written out under their own names
    ;@data:VP_DIAG vp_prseg ...           ...only when the part is assembled
                                          -D VP_DIAG (this tool's -D too)
    ;@call vp_mfree os88real_prep ...     the package's ROUTINES: written out
                                          as PC_vp_mfree, so `call vp_mfree`
                                          in the part stays an assembly error
                                          (a near call into the PART's own
                                          segment at the package's offset is
                                          silent and wrong) and the part's
                                          trampoline macro is the only way to
                                          name one

and the names come out of the map the package's own assembly wrote beside
it (the Makefile's STKLST), which describes that .bin and no other. A name
the map has not got fails the build, naming it. VK_LINKIMG is the image's
size from PKG.bin's header: the part carries it and the package refuses a
part linked against another build of itself.
"""
import argparse
import re
import struct
import sys


def mapsyms(path):
    out = {}
    for ln in open(path):
        f = ln.split()
        if len(f) == 3 and all(re.fullmatch(r"[0-9A-Fa-f]+", x) for x in f[:2]):
            out[f[2]] = int(f[0], 16)
        elif len(f) == 2 and re.fullmatch(r"[0-9A-Fa-f]{8}", f[0]):
            out[f[1]] = int(f[0], 16)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bin")
    ap.add_argument("map")
    ap.add_argument("part")
    ap.add_argument("-o", required=True)
    ap.add_argument("-D", action="append", default=[],
                    help="a define the part is assembled with, for a "
                    "`;@data:NAME` line")
    a = ap.parse_args()
    defs = {d.split("=")[0] for d in a.D}
    image = struct.unpack_from("<H", open(a.bin, "rb").read(), 8)[0]
    syms = mapsyms(a.map)
    data, call = [], []
    for ln in open(a.part):
        m = re.match(r";@(data|call)(?::(\w+))?\s+(.*)", ln)
        if m and (m.group(2) is None or m.group(2) in defs):
            (data if m.group(1) == "data" else call).extend(m.group(3).split())
    missing = [n for n in data + call if n not in syms]
    if missing:
        sys.exit("os88plink: %s takes %s, which %s has not got"
                 % (a.part, " ".join(missing), a.map))
    with open(a.o, "w") as f:
        f.write("; GENERATED by tools/os88plink.py from %s - do not edit\n"
                % a.map)
        f.write("VK_LINKIMG equ 0x%04X\n" % image)
        for n in data:
            f.write("%s equ 0x%04X\n" % (n, syms[n]))
        for n in call:
            f.write("PC_%s equ 0x%04X\n" % (n, syms[n]))
    return 0


if __name__ == "__main__":
    sys.exit(main())

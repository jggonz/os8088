#!/usr/bin/env python3
"""brpxlink: PiXEL's decoder parts' host variables, by name, out of the
Browser's PART 1 (SPEC.md 71.30).

    python3 tools/brpxlink.py build/browser.imgpart.map \\
            build/browser.imgpart.bin -o build/brpx/pxlink.inc

tools/pxlink.py links a PiXEL part against PiXEL's package; this links the
same source against the Browser's image part, which hosts it. Every symbol
part 1 defines between `bri_pxhost` and `bri_pxhend` - its block of the
names apps/pixel/pxjpeg.asm and pxpng.asm read through DS - is written out
as an equate, and nothing else, so a part's `call` into code it does not
have stays an assembly error. The map must be the one NASM wrote beside the
binary (`[map all]`, the Makefile's), so its length is checked against it.
PXL_IMAGE and PXL_BSS are the words at 8 and 10 of the host, which is what a
part that checks its stamp (the SIMPLE part; these two do not) compares.
"""
import argparse
import re
import struct
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("map")
    ap.add_argument("bin")
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    data = open(a.bin, "rb").read()
    syms = {}
    for line in open(a.map, encoding="latin-1"):
        m = re.match(r"\s+([0-9A-F]+)\s+([0-9A-F]+)\s+(\S+)\s*$", line)
        if m:
            syms[m.group(3)] = int(m.group(1), 16)
    if "bri_pxhost" not in syms or "bri_pxhend" not in syms:
        sys.exit("brpxlink: no bri_pxhost..bri_pxhend block in %s" % a.map)
    lo, hi = syms["bri_pxhost"], syms["bri_pxhend"]
    if hi > len(data):
        sys.exit("brpxlink: %s does not describe %s" % (a.map, a.bin))
    out = sorted((v, n) for n, v in syms.items()
                 if lo <= v < hi and "." not in n and n.startswith("px_"))
    if not out:
        sys.exit("brpxlink: the host block names nothing")
    image, bss = struct.unpack_from("<HH", data, 8)
    lines = ["; GENERATED by tools/brpxlink.py from %s - do not edit "
             "(SPEC.md 71.30)" % a.map.split("/")[-1],
             "; part 1's host block, by name, for PiXEL's decoder parts",
             "PXL_IMAGE   equ %d" % image,
             "PXL_BSS     equ %d" % bss]
    lines += ["%-24s equ 0x%04X" % (n, v) for v, n in out]
    open(a.o, "w").write("\n".join(lines) + "\n")
    print("brpxlink: %d host variables into %s" % (len(out), a.o))
    return 0


if __name__ == "__main__":
    sys.exit(main())

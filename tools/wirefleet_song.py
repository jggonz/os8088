#!/usr/bin/env python3
"""WireFleet's music track, written as text, -> apps/wirefleet/wfsong.inc.

SPEC.md 114.11. "Ironclad" is an original sea march in D minor, 16 bars of
4/4 in eighth notes, three voices: a melody, a bass and a held harmony. The
package's sequencer (wfsound.inc) plays all three on FM channels it claims
from SOUND.DRV, and the melody alone through the tone router on a machine
whose tone route is the PC speaker.

Row: db ticks, melody, bass, harmony, melody-length. A note byte is an index
into wf_bgmhz (1 = C2), 0 a rest (the voice is keyed off) and HOLD (0FEh) a
voice left sounding; the fifth byte is how many ticks the melody note lasts
from this row, which is what the speaker's self-expiring tone is given.
A row of ticks 0 ends the track and the sequencer loops. Standard library
only; --check detects drift.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'apps/wirefleet/wfsong.inc'
EIGHTH = 3                      # ticks: 165 ms, a march at ~91 crotchets
HOLD = 0xFE
NAMES = {'C': 0, 'C#': 1, 'Db': 1, 'D': 2, 'D#': 3, 'Eb': 3, 'E': 4, 'F': 5,
         'F#': 6, 'Gb': 6, 'G': 7, 'G#': 8, 'Ab': 8, 'A': 9, 'A#': 10,
         'Bb': 10, 'B': 11}

# Melody, one bar a line: note+octave and its length in eighths, r a rest.
MELODY = '''
D4 2 F4 1 A4 1 D5 3 C5 1
A4 2 F4 2 D4 4
Bb4 2 A4 1 G4 1 F4 2 D4 2
E4 2 G4 2 C5 3 Bb4 1
A4 3 F4 1 D5 2 A4 2
Bb4 2 D5 2 G4 3 A4 1
E4 2 A4 2 C#5 2 E5 2
A4 6 r 2
C5 2 A4 1 C5 1 F5 3 E5 1
D5 2 C5 2 G4 4
F4 2 A4 2 D5 3 C5 1
C#5 2 E5 2 A4 4
D5 2 Bb4 1 D5 1 F5 3 D5 1
E5 2 C5 2 G4 3 E4 1
F4 2 E4 1 F4 1 A4 2 C#5 2
D5 6 r 2
'''
# One chord a bar: the bass walks root-fifth-root-fifth in quarters, the
# harmony holds the chord's third for each half bar.
CHORDS = '''
D2 A2 F3   D2 A2 F3   Bb1 F2 D3   C2 G2 E3
D2 A2 F3   G2 D2 Bb3  A1 E2 C#4   A1 E2 C#4
F2 C3 A3   C2 G2 E3   D2 A2 F3    A1 E2 C#4
Bb1 F2 D3  C2 G2 E3   A1 E2 C#4   D2 A2 F3
'''


def note(name):
    """1-based index from C2; Bb1 and A1 are folded up an octave, because
    the bass's register is what the table pays for."""
    letter = name[:-1]
    octave = int(name[-1])
    n = (octave - 2) * 12 + NAMES[letter] + 1
    while n < 1:
        n += 12
    return n


def build():
    mel = []                                    # per eighth: (code, length)
    for bar in MELODY.strip().splitlines():
        t = bar.split()
        cells = 0
        for name, length in zip(t[0::2], t[1::2]):
            length = int(length)
            code = 0 if name == 'r' else note(name)
            mel.append((code, length))
            mel += [(HOLD, 0)] * (length - 1)
            cells += length
        if cells != 8:
            raise ValueError('a bar of %d eighths: %s' % (cells, bar))
    chords = CHORDS.split()
    chords = [chords[i:i + 3] for i in range(0, len(chords), 3)]
    if len(chords) * 8 != len(mel):
        raise ValueError('%d chords for %d bars' % (len(chords), len(mel) // 8))
    bass, harm = [], []
    for root, fifth, third in chords:
        for quarter in (root, fifth, root, fifth):
            bass += [note(quarter), HOLD]
        harm += [note(third)] + [HOLD] * 3 + [note(third)] + [HOLD] * 3
    rows = []
    for m, b, h in zip(mel, bass, harm):
        if rows and m[0] == b == h == HOLD:
            rows[-1][0] += EIGHTH               # nothing changes: lengthen
            continue
        rows.append([EIGHTH, m[0], b, h, m[1] * EIGHTH])
    hz = [0] + [round(65.406 * 2 ** (i / 12)) for i in range(48)]
    top = max(x for r in rows for x in r[1:4] if x != HOLD)
    if top >= len(hz):
        raise ValueError('a note above the table')
    out = ['; Generated by tools/wirefleet_song.py; do not edit. SPEC.md 114.11.',
           '; "Ironclad": db ticks, melody, bass, harmony, melody ticks.',
           'WF_BGM_HOLD equ 0%02Xh' % HOLD, 'align 2', 'wf_bgmhz:']
    for i in range(0, len(hz), 12):
        out.append('    dw ' + ','.join(str(v) for v in hz[i:i + 12]))
    out.append('wf_song:')
    for i in range(0, len(rows), 4):
        out.append('    db ' + ', '.join(','.join(str(v) for v in r)
                                         for r in rows[i:i + 4]))
    out.append('    db 0                        ; the end: loop')
    return '\n'.join(out) + '\n', rows


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    data, rows = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != data:
            p.error('stale wfsong.inc; run python3 tools/wirefleet_song.py')
    else:
        OUTPUT.write_text(data)
    ticks = sum(r[0] for r in rows)
    print('wirefleet_song: %d rows, %d bytes, %.1f s a loop' %
          (len(rows), len(rows) * 5 + 1, ticks / 18.2065))


if __name__ == '__main__':
    main()

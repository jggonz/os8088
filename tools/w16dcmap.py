#!/usr/bin/env python3
"""w16dcmap.py - where the DOS core's int 21h gate is (SPEC.md 124.21.1).

    w16dcmap.py --core build/doscore.bin -o build/win16/w16dcore.inc [nasm flags]

WIN16 hosts DOS.O88's core, the one assembled `build/doscore.bin`, and enters
it through its `int 21h` gate, `dos_int21`. The core publishes its surface as
a jump table (apps/dos/doscents.inc) and the gate is not on it: neither
DOS.O88 nor kern_dos ever needed it by address, and a slot would cost the
core three bytes and kern_dos a kilobyte rung. So this reads the address off
a symbol map instead - of the SAME assembly: it assembles doscore.asm again
with a map, refuses unless the bytes are identical to the core WIN16 ships,
and writes one equate.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--core", required=True)
    ap.add_argument("-o", required=True)
    ap.add_argument("--nasm", default="nasm")
    a, flags = ap.parse_known_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with tempfile.TemporaryDirectory() as t:
        src = os.path.join(t, "dcmap.asm")
        mp = os.path.join(t, "dc.map")
        out = os.path.join(t, "dc.bin")
        with open(src, "w") as f:
            f.write("[map symbols %s]\n%%include \"doscore.asm\"\n" % mp)
        cmd = a.nasm.split() + ["-f", "bin", "-w+error"] + flags + ["-o", out, src]
        subprocess.run(cmd, check=True, cwd=root)
        if open(out, "rb").read() != open(a.core, "rb").read():
            sys.exit("w16dcmap: the map's assembly is not %s - flags differ" % a.core)
        addr = None
        for line in open(mp):
            m = re.match(r"\s*([0-9A-Fa-f]+)\s+[0-9A-Fa-f]+\s+dos_int21\s*$", line)
            if m:
                addr = int(m.group(1), 16)
        if addr is None:
            sys.exit("w16dcmap: no dos_int21 in the core's map")
    with open(a.o, "w") as f:
        f.write("; GENERATED by tools/w16dcmap.py from %s - do not edit\n"
                "W16_DOSINT21 equ 0x%04X      ; the core's int 21h gate\n"
                % (os.path.basename(a.core), addr))
    print("w16dcmap: dos_int21 at %04Xh" % addr)


if __name__ == "__main__":
    main()

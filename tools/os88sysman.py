#!/usr/bin/env python3
"""os88sysman: System Check's release manifest (SPEC.md 118.2).

    python3 tools/os88sysman.py --kernel build/KERNEL.SYS \\
        --retired apps/syscheck/retired.txt -o build/syscheck_man.inc \\
        build/sound.drv ... SYSTEM:build/taskmgr.o88 STIKAPPS:build/deskcal.o88
    python3 tools/os88sysman.py --selfcheck

Writes the NASM data SYSCHECK.O88 `%include`s: one entry per file the
kern_big system disk carries - its kind, its folder, its size and the
Fletcher-style sum (SPEC.md 118.2) over its bytes AS STORED - then the
retired names. The arguments are the system disk's own INPUTS, in
`tools/os88disk.py`'s spelling (a bare path lands in the root, `SYSTEM:` and
`STIKAPPS:` in those folders), because the image depends on SYSCHECK.O88 and
a manifest read off it would be a cycle (SPEC.md 118.2.1). os88disk copies a
file as it is given, so these bytes ARE the disk's - which
tests/unit/t_sysman.py holds against every built system disk.

`sums()` is the one definition of the sum on the host; the package's
sc_sum is the other, and t_sysman compares them through the manifest.
"""

import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import os88drv  # noqa: E402
from os88mod import MOD_VER  # noqa: E402  (kernel/mod.inc, mirrored there)

# kinds and folders - mirrored in apps/syscheck/syscheck.asm (SCK_*, SCF_*)
SCK_KERNEL = 1
SCK_BOOT = 2
SCK_DRV = 3
SCK_MOD = 4
SCK_PKG = 5
KINDS = {SCK_KERNEL: "kernel", SCK_BOOT: "boot file", SCK_DRV: "driver",
         SCK_MOD: "module", SCK_PKG: "package"}
FOLDERS = {"": 0, "SYSTEM": 1, "STIKAPPS": 2}

MAGIC = b"O8"


def fail(msg):
    print(f"os88sysman: error: {msg}", file=sys.stderr)
    sys.exit(1)


def sums(data):
    """SPEC.md 118.2: s1 += b, s2 += s1, both mod 65536, from 0."""
    s1 = s2 = 0
    for b in data:
        s1 = (s1 + b) & 0xFFFF
        s2 = (s2 + s1) & 0xFFFF
    return s1, s2


def name83(path):
    base = os.path.basename(path).upper()
    stem, _, ext = base.partition(".")
    if not stem or len(stem) > 8 or len(ext) > 3:
        fail(f"{path}: {base} is not an 8.3 name")
    return base


def classify(name, blob):
    """A file's kind from its own header, never from its name alone."""
    if name.endswith(".O88"):
        return SCK_PKG
    if name.endswith(".DRV"):
        img = os88drv.image_unwrap(blob)
        if img[:2] != MAGIC:
            fail(f"{name}: not an 'O8' image")
        if img[2] == os88drv.DRV_VER:
            return SCK_DRV
        if img[2] == MOD_VER:
            return SCK_MOD
        fail(f"{name}: header version {img[2]} is neither DRV_VER "
             f"{os88drv.DRV_VER} nor MOD_VER {MOD_VER}")
    return SCK_BOOT


def split(arg):
    folder, sep, path = arg.partition(":")
    if not sep or os.sep in folder or "/" in folder:
        return "", arg
    if folder.upper() not in FOLDERS:
        fail(f"{arg}: folder {folder!r} is not one System Check knows")
    return folder.upper(), path


def build(kernel, files, retired):
    rows, seen = [], set()
    blob = open(kernel, "rb").read()
    rows.append((SCK_KERNEL, 0, "KERNEL.SYS", len(blob), sums(blob)))
    seen.add((0, "KERNEL.SYS"))
    for arg in files:
        folder, path = split(arg)
        name = name83(path)
        key = (FOLDERS[folder], name)
        if key in seen:
            fail(f"{name} is named twice in {folder or 'the root'}")
        seen.add(key)
        if name == "SYSCHECK.O88":
            fail("SYSCHECK.O88 cannot be in its own manifest (SPEC.md 118.2)")
        blob = open(path, "rb").read()
        rows.append((classify(name, blob), FOLDERS[folder], name, len(blob),
                     sums(blob)))
    names = []
    for line in open(retired):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        n = name83(line)
        if any(r[2] == n for r in rows):
            fail(f"{n} is retired and also ships (apps/syscheck/retired.txt)")
        names.append(n)
    return rows, names


def emit(rows, names):
    out = ["; GENERATED by tools/os88sysman.py - do not edit (SPEC.md 118.2)",
           "; kind, folder, size (dword), s1, s2, name NUL; a 0 kind ends it",
           f"SC_MANN equ {len(rows)}",
           f"SC_MANKB equ {sum(r[3] for r in rows) // 1024 + 1}"
           "    ; the manifest's bytes, for the progress bar",
           f"SC_NDRV equ {sum(1 for r in rows if r[0] in (SCK_DRV, SCK_MOD))}"
           "    ; drivers and modules, for the Drivers row",
           "sc_man:"]
    for kind, folder, name, size, (s1, s2) in rows:
        out.append(f"    db {kind}, {folder}\n    dd {size}\n"
                   f"    dw 0x{s1:04X}, 0x{s2:04X}\n    db '{name}', 0"
                   f"    ; {KINDS[kind]}")
    out.append("    db 0")
    out.append(f"SC_RETN equ {len(names)}")
    out.append("sc_retired:                     ; NUL names, an empty one ends it")
    for n in names:
        out.append(f"    db '{n}', 0")
    out.append("    db 0")
    return "\n".join(out) + "\n"


def read_inc(path):
    """The rows back out of an emitted .inc - t_sysman's reader."""
    rows, cur = [], None
    for line in open(path):
        s = line.split(";", 1)[0].strip()
        if s.startswith("db ") and "'" not in s and cur is None and s != "db 0":
            k, f = (int(v) for v in s[3:].split(","))
            cur = [k, f]
        elif cur is not None and s.startswith("dd "):
            cur.append(int(s[3:]))
        elif cur is not None and s.startswith("dw "):
            cur.append(tuple(int(v, 16) for v in s[3:].split(",")))
        elif cur is not None and s.startswith("db '"):
            cur.append(s.split("'")[1])
            k, f, size, sm, name = cur
            rows.append((k, f, name, size, sm))
            cur = None
        elif s.startswith("sc_retired"):
            break
    return rows


def selfcheck():
    assert sums(b"") == (0, 0)
    assert sums(b"\x01\x02") == (3, 4)
    assert sums(b"\xff" * 300)[0] == (255 * 300) & 0xFFFF
    # position-sensitive: the same bytes in another order differ in s2
    assert sums(b"ab")[1] != sums(b"ba")[1]
    assert split("SYSTEM:build/x.o88") == ("SYSTEM", "build/x.o88")
    assert split("build/x.drv") == ("", "build/x.drv")
    print("os88sysman: selfcheck ok")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--kernel")
    ap.add_argument("--retired")
    ap.add_argument("-o", "--out")
    ap.add_argument("--selfcheck", action="store_true")
    ap.add_argument("files", nargs="*")
    a = ap.parse_args()
    if a.selfcheck:
        return selfcheck()
    if not (a.kernel and a.retired and a.out):
        fail("--kernel, --retired and -o are all required")
    rows, names = build(a.kernel, a.files, a.retired)
    text = emit(rows, names)
    tmp = a.out + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, a.out)
    print(f"os88sysman: {len(rows)} files, {len(names)} retired names -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""os88mousekid - the kernel fingerprint MOUSECHK checks itself against.

    os88mousekid.py kernel.map kernel-full.bin -o build/mousechk_kid.inc

SPEC.md 126.4. MOUSECHK reads the kernel's debug registry (the one shipped
reader SPEC.md 57.3 allows) and decodes it only when the kernel is the build
the package was made with. "The build" is the 'ID' block (SPEC.md 57.6): three
words, `kbld_text`, `kbld_cold`, `kbld_blob`, that the kernel keeps as plain
assembly-time lengths. This reads those three words out of the kernel image the
build just made - at the file offset the NASM map gives `kbld_text`, the map's
first column - so the package and the kernel it ships beside cannot disagree,
and the numbers are never typed.

The output is a few `equ`s and nothing else: no path, no date, so a rebuild of
the same kernel writes the same bytes.
"""
import argparse
import re
import struct
import sys


def kbld_offset(map_path):
    """The file offset of kbld_text: column one of its map line."""
    pat = re.compile(r"^\s*([0-9A-Fa-f]+)\s+([0-9A-Fa-f]+)\s+kbld_text\s*$")
    for line in open(map_path):
        m = pat.match(line)
        if m:
            return int(m.group(1), 16)
    sys.exit("os88mousekid: kbld_text is not in %s - SPEC.md 57.6's block "
             "was renamed or removed" % map_path)


def words(map_path, image_path):
    off = kbld_offset(map_path)
    data = open(image_path, "rb").read()
    if off + 6 > len(data):
        sys.exit("os88mousekid: kbld_text at %#x is past the end of %s"
                 % (off, image_path))
    return struct.unpack_from("<3H", data, off)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("map")
    ap.add_argument("image")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    w = words(a.map, a.image)
    text = ("; generated by tools/os88mousekid.py - do not edit.\n"
            "; The kernel's 'ID' block (SPEC.md 57.6, 126.4) of the build "
            "this package ships beside.\n")
    for name, v in zip("ABC", w):
        text += "MC_KID_%s equ 0x%04X\n" % (name, v)
    try:                                # unchanged -> leave the mtime alone, so
        if open(a.out).read() == text:  # a kernel rebuild that moved nothing
            return                      # does not rebuild every disk
    except OSError:
        pass
    with open(a.out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
